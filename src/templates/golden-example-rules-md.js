const DRAFT_BANNER = `> **DRAFT — must be reviewed.** This file was auto-generated by \`caf-initiator\` as the
> mandatory companion to the golden example in this folder (see CAF.md Layer 1). Fill in the
> Do/Don't sections below manually — without this, the golden example is ambiguous and the AI
> has to guess for itself which parts are the pattern and which just happened to be in that file.
`;

// Reference-based: RULES.md never copies the file, it points at the real repo path — so the
// example stays "alive" and keeps changing alongside the codebase instead of drifting from a
// frozen snapshot. Trade-off: one extra lookup (read RULES.md → read the file at its path).
function buildReferenceTable(entries) {
  if (!entries || entries.length === 0) {
    return 'TODO: no reference files recorded yet — add `path`, `pattern`, `reason` rows manually.';
  }
  const header = '| Path | Pattern | Reason (Do/Don\'t) |\n|---|---|---|';
  const rows = entries.map((e) => `| \`${e.relPath}\` | ${e.patternName || 'TODO'} | TODO |`);
  return [header, ...rows].join('\n');
}

/**
 * Build the RULES.md that must accompany every .caf/knowledge/golden-examples/{{app}}/ folder.
 * Reference-based: `entries` are { relPath, patternName } pointing at the original file in the
 * codebase (never copied). Do/Don't reasoning is always left TODO — same pattern as ADR
 * Decision/Consequences.
 */
export function buildRulesMd({ appLabel, entries = [] }) {
  return `# Golden Examples — RULES.md${appLabel ? ` (${appLabel})` : ''}

${DRAFT_BANNER}
## Reference Files

The paths below point to the original file in the codebase (not a copy) — read this RULES.md
first for context, then open the actual file at the listed path.

${buildReferenceTable(entries)}

## Why the Files in This Folder Are Good Examples

TODO: explain why the files above were chosen as references — what pattern the AI should
imitate (e.g. thin controller, validated DTO, composable pattern, etc.).

## Do

TODO: which parts MUST be imitated from this example.

## Don't

TODO: which parts happen to be in this file but must NOT be imitated (e.g. a temporary
workaround, old code that hasn't been cleaned up yet).
`;
}

// Companion slash commands for ticket-driven roles: Planner, Architect, QA, Reviewer.
//
// The pattern here is DELIBERATELY different from discovery-commands.js: `/caf-discovery-start`
// spawns a subagent via the Task tool, whereas these four commands are **main-thread wrappers** —
// Claude reads the agent definition (`{kind}.md`) as the source of truth for the role, then
// impersonates that role itself in the main thread. No Task tool, no spawning.
//
// plan-ticket.md and qa-check.md were ported from umkm-pos (.claude/commands/, hand-written and
// already battle-tested) then generalized: project-specific module/stack names stripped out,
// tracker references made neutral. design-ticket.md and review-ticket.md are new, following the
// exact same pattern for the Architect and Reviewer roles.
//
// Frontend/Backend/Documentation DELIBERATELY have no preview command like this. Frontend/Backend
// write production code — if run manually while caf-orchestrator runs in parallel on the same
// ticket, two code writers would collide on the same working tree. Documentation has little value
// here because in the CAF design it's parallel/non-blocking by nature. Don't add a builder for
// these three roles to this file.
//
// The manual path for code-writing roles lives in templates/caf-run-pipeline-command.js
// (`/caf-run-pipeline`) — and precisely because of the collision risk above, that command is NOT
// a per-role preview: it's opt-in via explicit confirmation and opens a run with local+remote
// branch guards before touching anything. That difference is deliberate; don't "simplify" it by
// moving Frontend/Backend into this file's preview pattern.

const DRAFT_BANNER =
  '> DRAFT generated by caf-initiator — review and complete before use, especially the\n' +
  '> sections marked TODO project-specific.';

/**
 * Block that MUST be identical across all four commands: this command is a manual preview, not a
 * pipeline trigger. That's exactly where its value lies — a cheap sanity check before burning the
 * cost of a full run.
 *
 * `extra` is for a stage-specific closing note (e.g. qa-check suggesting CRITICAL issues be fixed
 * first before triggering the pipeline).
 */
function notAPipelineTrigger({ readyLabel, extra = '' }) {
  const base = `## After Completion

**This command does NOT trigger \`caf-orchestrator\` or any automated pipeline.**
No downstream agent is spawned, no ticket status is changed, no comment/PR is posted to the
tracker. The only output is a local file in \`.caf/tasks/{TICKET-ID}/\` for a human to read.

If the user agrees with this preview and wants to proceed to the automated pipeline, they
still have to do it themselves as usual (${readyLabel}) — remind them of this at the end of the
run, don't let the user think the pipeline has already started.`;
  return extra ? `${base}\n\n${extra}` : base;
}

/**
 * Command-level non-destructive rule. Different context from `writeIfAbsent` in the generator:
 * this is an interactive command the user runs repeatedly against the same ticket, so "already
 * exists" doesn't mean silently skip — the user decides.
 */
function nonDestructiveRule(artifacts) {
  const list = artifacts.map((a) => `\`.caf/tasks/{TICKET-ID}/${a}\``).join(' and ');
  return `## Save the Output

MUST write the output to ${list} — don't just display it in chat.

Before writing, check whether the target file already exists:

- **Doesn't exist** → create the folder if needed, write, continue.
- **Already exists** → DO NOT overwrite it directly. Show the user a summary of the current
  content and ask what to do: overwrite (this run's result replaces it), save as a comparison
  file, or cancel. STOP until the user answers.`;
}

function agentSourceOfTruth({ agentDir, kind, roleLabel, fallback }) {
  return `## Follow the ${roleLabel} Agent's Pattern

If \`${agentDir}/${kind}.md\` exists, **read that file and follow its content as the primary
source of truth** for scope, working pattern, and output format — not the instructions in this
command. This command is just a wrapper: you run the ${roleLabel} role in the main thread,
without spawning a subagent.

If that file doesn't exist, use the following default:

${fallback}`;
}

function ticketSection({ optionalFocus = false } = {}) {
  const focus = optionalFocus
    ? `

The argument may be followed by an optional focus area after TICKET-ID (e.g.
\`GAN-44 checkout form validation\`). If present, narrow the review to that area — but still
report any obvious issues outside the focus area that come up along the way.`
    : '';
  return `## Ticket

Ticket ID: \`$ARGUMENTS\`

REQUIRED. If empty, ask the user which ticket they mean and STOP until answered —
don't guess.

Fetch the ticket details (title, description, acceptance criteria): if an MCP tracker
(Linear/Jira/GitHub Issues) is connected, use it. Otherwise, ask the user to paste the
ticket details manually before continuing — don't invent requirements that weren't stated.${focus}`;
}

function previewCommandMd({
  allowedTools,
  description,
  argumentHint,
  title,
  writeScope,
  purpose,
  agentDir,
  kind,
  roleLabel,
  fallback,
  input,
  outputFormat,
  artifacts,
  readyLabel,
  afterExtra,
  optionalFocus = false,
}) {
  return `---
allowed-tools: ${allowedTools}
description: ${description}
argument-hint: ${argumentHint}
---

${DRAFT_BANNER}

# ${title}

**${writeScope}**

${purpose}

${ticketSection({ optionalFocus })}

${input ? `## Input\n\n${input}\n\n` : ''}${agentSourceOfTruth({ agentDir, kind, roleLabel, fallback })}

## Output Format

${outputFormat}

${nonDestructiveRule(artifacts)}

${notAPipelineTrigger({ readyLabel, extra: afterExtra })}
`;
}

const READY_LABEL_TRACKER =
  'set the ticket status to "Ready for AI" in the tracker, or whatever trigger this project uses';

/**
 * plan-ticket.md — generalized from umkm-pos/.claude/commands/plan-ticket.md.
 */
export function buildPlanTicketMd({ agentDir = '.claude/agents' } = {}) {
  return previewCommandMd({
    agentDir,
    kind: 'planner',
    roleLabel: 'Planner',
    allowedTools: 'Read, Write, Grep, Glob, Bash(ls:*), Bash(git branch:*), Bash(git status:*)',
    description:
      'Preview the Planner Agent\'s plan for a single ticket (requirements.md + tasks.md) without triggering the full pipeline',
    argumentHint: '[TICKET-ID, e.g. "GAN-44"]',
    title: 'Plan Ticket (Preview, Manual)',
    writeScope:
      'This command is READ-MOSTLY. It may write only to `.caf/tasks/{TICKET-ID}/` ' +
      '(requirements.md, tasks.md) — DO NOT touch any application code.',
    purpose: `Purpose: preview the planning result BEFORE this ticket actually enters the automated pipeline.
Useful for a manual sanity check without the consequence of spawning implementation/QA/Reviewer
agents — if the plan turns out to be off-target, it's caught here, not after the full pipeline has run.`,
    fallback: `1. Read the ticket, understand the acceptance criteria.
2. Identify which app/module is affected — **verify from the actual project structure**
   (package.json, workspace config, folder contents), don't assume from the ticket name.
3. Break it down into concrete tasks, ordered by dependency between tasks.
4. If there's a contract gap between layers (e.g. a field the frontend needs isn't in the
   backend response yet), record it as an explicit finding — that's actually a sign planning is
   working correctly, not a sign the ticket is incomplete.
5. If the ticket is too ambiguous to break down with confidence, report the ambiguity
   explicitly — DO NOT guess requirements that weren't stated.`,
    outputFormat: `Two files, in a format consistent with what the automated pipeline uses (if another ticket has
already run in \`.caf/tasks/\`, use it as the format reference before inventing your own):

\`\`\`
requirements.md
## Context             ← ticket summary + affected app/module
## Acceptance Criteria ← one checklist line per criterion
## Out of Scope        ← what is deliberately NOT done in this ticket
## Gaps & Ambiguities  ← unresolved contracts between layers, unclear requirements

tasks.md
## Tasks
- [ ] 1. <concrete task> — app/module, dependency on which task number
\`\`\`

When done, show the user a brief summary: how many tasks, which apps are affected, whether
there are any ambiguities or contract gaps.`,
    artifacts: ['requirements.md', 'tasks.md'],
    readyLabel: READY_LABEL_TRACKER,
  });
}

/**
 * design-ticket.md — new, follows the exact same pattern as plan-ticket for the Architect role.
 * The `design.md` artifact follows CAF.md Layer 3.
 */
export function buildDesignTicketMd({ agentDir = '.claude/agents' } = {}) {
  return previewCommandMd({
    agentDir,
    kind: 'architect',
    roleLabel: 'Architect',
    allowedTools: 'Read, Write, Grep, Glob, Bash(ls:*)',
    description:
      'Preview the Architect Agent\'s technical approach for a single ticket (design.md) without triggering the full pipeline',
    argumentHint: '[TICKET-ID, e.g. "GAN-44"]',
    title: 'Design Ticket (Preview, Manual)',
    writeScope:
      'This command is READ-MOSTLY. It may write only to `.caf/tasks/{TICKET-ID}/design.md` — ' +
      'DO NOT touch any application code, migrations, or schema.',
    purpose: `Purpose: preview technical decisions BEFORE the ticket enters the automated pipeline. Architect
is an optional role in CAF — used for tasks that involve a new schema, multiple services, or a
non-trivial architectural decision. If, after reading the ticket, the task turns out to be
simple and doesn't need an architectural decision, **say so to the user and stop** — don't
invent a design doc for a task that doesn't need one.`,
    input: `\`.caf/tasks/{TICKET-ID}/requirements.md\` from the Planner (run \`/caf-plan-ticket\` first if it
doesn't exist yet, or ask the user to paste the requirements).

Optional, if available in this project — read as additional context, not a hard requirement:
- \`docs/architecture/system-overview.md\`
- \`docs/api-contract.md\`
- \`docs/schema/erd.md\`
- relevant ADRs in \`.caf/knowledge/decisions/\``,
    fallback: `1. Read \`requirements.md\`, identify what technical decisions actually need to be made.
2. Map the components involved — **verify from the actual code structure**, don't assume
   module/service names from the ticket name.
3. For each decision: write the options considered, the choice made, and the reasoning.
   A single option with no alternative isn't an architectural decision — that's just
   ordinary implementation.
4. Check consistency with existing ADRs in \`.caf/knowledge/decisions/\`. If the proposed
   approach conflicts with an active ADR, say so explicitly — that needs a new ADR
   (a human decision), not a silent violation.
5. If the requirements aren't enough to make a technical decision with confidence,
   report what's missing — DO NOT guess.`,
    outputFormat: `\`\`\`
design.md
## Context               ← requirements summary + why this task needs an Architect
## Affected Components   ← real files/modules/services (verified, not assumed)
## Technical Decisions
### <decision 1>
- Options considered
- Choice + reasoning
- Consequences / trade-offs
## Cross-Layer Contracts ← shape of data flowing between apps/services, if any
## Risks & Mitigations
## ADR Impact            ← which ADRs it aligns with; whether a new ADR is needed
## Open Questions        ← what can't be decided without a human answer
\`\`\`

When done, show the user a brief summary: how many technical decisions were made, whether
there's any conflict with an ADR, whether there are open questions.`,
    artifacts: ['design.md'],
    readyLabel: READY_LABEL_TRACKER,
    afterExtra: `If there's an \`## Open Questions\` section with unanswered items, suggest the user resolve
those first before triggering the pipeline — the implementation agent will guess if the design
is left hanging, and the guess won't be caught as wrong until after the code is written.`,
  });
}

/**
 * qa-check.md — generalized from umkm-pos/.claude/commands/qa-check.md. Different from the other
 * three commands: it needs unrestricted Bash because it runs the project's verification scripts
 * (lint/typecheck/test), whose names are only known at runtime from package.json.
 */
export function buildQaCheckMd({ agentDir = '.claude/agents' } = {}) {
  return previewCommandMd({
    agentDir,
    kind: 'qa',
    roleLabel: 'QA',
    // TODO project-specific: `Bash` here is deliberately unscoped unlike the other commands
    // because the verification script names (lint/typecheck/test) are only known at runtime
    // from package.json. Once you know the scripts, narrow it to e.g.
    // `Bash(pnpm run lint:*), Bash(pnpm run typecheck:*), Bash(git diff:*)`.
    allowedTools: 'Read, Write, Grep, Glob, Bash',
    description:
      'Run the quality gate + a manual QA checklist on the local branch/diff, before opening a PR or triggering the pipeline',
    argumentHint: '[TICKET-ID, e.g. "GAN-44"]',
    title: 'QA Check (Preview, Manual)',
    writeScope:
      'This command is READ-ONLY with respect to application code. It may run lint/typecheck/test ' +
      'via Bash and write only to `.caf/tasks/{TICKET-ID}/qa-report.md` — DO NOT auto-edit/fix ' +
      'code. This command is for REPORTING status, not fixing it.',
    purpose: `Purpose: a manual self-check on the local branch before code is sent to the automated pipeline or
before opening a PR — so basic issues are caught early, instead of waiting for the QA Agent in
the full pipeline, which costs much more.`,
    optionalFocus: true,
    input: `Diff from the base branch. Detect the base branch from config/git — check \`caf.config.yaml\`
field \`repo.baseBranch\` if present; don't assume a branch name without verifying it.

If \`.caf/tasks/{TICKET-ID}/requirements.md\` exists, use it as the acceptance criteria reference.`,
    fallback: `1. **Quality Gate** — run commands that actually exist in \`package.json\`
   (verify the script names first, don't assume \`npm run lint\` exists):
   - typecheck
   - lint
   - test (if there are tests relevant to the diff)
2. **Acceptance Criteria** — if a relevant \`requirements.md\` exists, check each criterion
   one by one, and include a code line reference (\`file:line\`) for each one that PASSes. A
   criterion with no evidence is not PASS.
3. **Edge Cases** — identify edge case scenarios relevant to the change (validation
   failure, error handling, race condition, empty state), report which are already covered by
   code/tests and which aren't.
4. **Security Check** (if there are backend changes) — TODO project-specific: adjust this
   list to the project's real risks. Common checkpoints: data scoping across tenants/users,
   authorization coverage on new endpoints, raw SQL/query injection, secrets or sensitive data
   leaking into logs/responses.`,
    outputFormat: `Same format as the \`qa-report.md\` used by the automated pipeline:

\`\`\`
## Status: PASS / NEEDS_HUMAN

## Quality Gate Results
- Typecheck: PASS/FAIL
- Lint: PASS/FAIL
- Test: PASS/FAIL/SKIP (reason)

## Acceptance Criteria
- [ ] <criterion> — status, evidence file:line

## Edge Cases
| Scenario | Expected | Actual | Status |

## Issues Found
### CRITICAL
### NON-CRITICAL
\`\`\`

If any quality gate FAILs, include the actual error output verbatim —
don't summarize it as "there's a lint error".`,
    artifacts: ['qa-report.md'],
    readyLabel: READY_LABEL_TRACKER,
    afterExtra: `This report is also NOT posted to the tracker/PR. If everything PASSes, the user can proceed to
open a PR manually or trigger the pipeline with more confidence. If there's a CRITICAL issue,
suggest the user fix it first before triggering the full pipeline — to avoid wasting pipeline
time/cost on code that's already known to have problems.`,
  });
}

/**
 * review-ticket.md — new, follows the exact same pattern for the Reviewer role. The
 * `review-notes.md` artifact follows CAF.md Layer 3.
 */
export function buildReviewTicketMd({ agentDir = '.claude/agents' } = {}) {
  return previewCommandMd({
    agentDir,
    kind: 'reviewer',
    roleLabel: 'Reviewer',
    allowedTools:
      'Read, Write, Grep, Glob, Bash(git diff:*), Bash(git log:*), Bash(git status:*), Bash(git branch:*), Bash(ls:*)',
    description:
      'Manual qualitative review of a single ticket\'s implementation (review-notes.md) without triggering the full pipeline',
    argumentHint: '[TICKET-ID, e.g. "GAN-44"]',
    title: 'Review Ticket (Preview, Manual)',
    writeScope:
      'This command is READ-ONLY with respect to application code. It may write only to ' +
      '`.caf/tasks/{TICKET-ID}/review-notes.md` — DO NOT fix any code you find to be ' +
      'problematic. Review reports, it doesn\'t patch.',
    purpose: `Purpose: a manual qualitative review before opening a PR or before the ticket enters the
automated pipeline. Unlike \`/caf-qa-check\`, which answers "does it work or not", this command
answers "is it mergeable or not": consistency with project conventions, structural quality,
risks that don't show up in green test results.`,
    input: `The complete implementation in the context of the ticket — **not just the diff**. Read the
changed files in full, since structural problems often aren't visible from a diff snippet.

Detect the base branch from \`caf.config.yaml\` field \`repo.baseBranch\` if present; don't assume
a branch name without verifying it.

Optional, if available in \`.caf/tasks/{TICKET-ID}/\` — read as context, not a requirement:
- \`requirements.md\` (reference: does the implementation match what was requested)
- \`design.md\` (reference: does the implementation deviate from the agreed design)
- \`qa-report.md\` (to avoid repeating findings QA already reported)`,
    fallback: `1. **Alignment with the ticket** — does the code actually match what the requirements asked
   for? Any scope creep (changes outside the ticket) or any missed requirement?
2. **Convention consistency** — compare against existing surrounding code: naming,
   folder structure, error handling pattern, layering. Verify from actual code, not from
   general preferences.
3. **ADR compliance** — check \`.caf/knowledge/decisions/\`. If an active ADR is being
   violated, that's a finding, regardless of the reason.
4. **Structure & duplication** — logic duplicated from existing code, leaky abstractions
   between layers, functions doing too much.
5. **Risk** — TODO project-specific: adjust to the project's real risks. Common checkpoints:
   data scoping across tenants/users, authorization coverage, error handling that silently
   swallows exceptions, non-reversible schema/migration changes, sensitive data leaking into
   logs/responses.
6. If you don't find any significant issues, **say so plainly** — don't invent minor
   findings just to make the report look substantial.`,
    outputFormat: `\`\`\`
review-notes.md
## Status: APPROVE / REQUEST_CHANGES / NEEDS_HUMAN

## Change Summary
<what changed, in 2-3 sentences>

## Alignment with Ticket
- [ ] <requirement> — met / not met, evidence file:line

## Findings
### BLOCKING
- <file:line> — issue, why it's blocking, suggested fix

### NON-BLOCKING
- <file:line> — issue, suggested fix

## ADR Compliance
<which ADRs are relevant, followed or violated>

## Notes for a Human
<items needing a human decision, not technical findings>
\`\`\`

Every finding MUST have a \`file:line\` location. A finding without a location can't be
acted on — find the location or don't report it.`,
    artifacts: ['review-notes.md'],
    readyLabel: READY_LABEL_TRACKER,
    afterExtra: `This review is also NOT posted as a PR comment. If there's a BLOCKING finding, suggest the
user fix it first before opening a PR or triggering the pipeline.`,
  });
}

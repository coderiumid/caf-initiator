// Companion slash command for the Planner: /caf-plan-ticket.
//
// The pattern here is DELIBERATELY different from discovery-commands.js: a command that spawns a
// subagent via the Task tool, whereas this command is a **main-thread wrapper** —
// Claude reads the agent definition (`{kind}.md`) as the source of truth for the role, then
// impersonates that role itself in the main thread. No Task tool, no spawning.
//
// plan-ticket.md was ported from umkm-pos (.claude/commands/, hand-written and already
// battle-tested) then generalized: project-specific module/stack names stripped out, tracker
// references made neutral. (The design-ticket, qa-check and review-ticket builders were removed
// at CAF-SDD-03c3: no scaffold writes those commands.)
//
// Frontend/Backend/Documentation DELIBERATELY have no preview command like this. Frontend/Backend
// write production code — if run manually while caf-orchestrator runs in parallel on the same
// ticket, two code writers would collide on the same working tree. Documentation has little value
// here because in the CAF design it's parallel/non-blocking by nature. Don't add a builder for
// these three roles to this file.
//
// The manual path for code-writing roles lives in templates/run-pipeline-command.js
// (`/caf-run`) — and precisely because of the collision risk above, that command is NOT
// a per-role preview: it's opt-in via explicit confirmation and opens a run with local+remote
// branch guards before touching anything. That difference is deliberate; don't "simplify" it by
// moving Frontend/Backend into this file's preview pattern.

const DRAFT_BANNER =
  '> DRAFT generated by caf-initiator — review and complete before use, especially the\n' +
  '> sections marked TODO project-specific.';

/**
 * Block that MUST be identical across all four commands: this command is a manual preview, not a
 * pipeline trigger. That's exactly where its value lies — a cheap sanity check before burning the
 * cost of a full run.
 *
 * `extra` is for a stage-specific closing note (e.g. qa-check suggesting CRITICAL issues be fixed
 * first before triggering the pipeline).
 */
function notAPipelineTrigger({ readyLabel, extra = '' }) {
  const base = `## After Completion

**This command does NOT trigger \`caf-orchestrator\` or any automated pipeline.**
No downstream agent is spawned, no ticket status is changed, no comment/PR is posted to the
tracker. The only output is a local file in \`.caf/tasks/{TICKET-ID}/\` for a human to read.

If the user agrees with this preview and wants to proceed to the automated pipeline, they
still have to do it themselves as usual (${readyLabel}) — remind them of this at the end of the
run, don't let the user think the pipeline has already started.`;
  return extra ? `${base}\n\n${extra}` : base;
}

/**
 * Command-level non-destructive rule. Different context from `writeIfAbsent` in the generator:
 * this is an interactive command the user runs repeatedly against the same ticket, so "already
 * exists" doesn't mean silently skip — the user decides.
 */
function nonDestructiveRule(artifacts) {
  const list = artifacts.map((a) => `\`.caf/tasks/{TICKET-ID}/${a}\``).join(' and ');
  return `## Save the Output

MUST write the output to ${list} — don't just display it in chat.

Before writing, check whether the target file already exists:

- **Doesn't exist** → create the folder if needed, write, continue.
- **Already exists** → DO NOT overwrite it directly. Show the user a summary of the current
  content and ask what to do: overwrite (this run's result replaces it), save as a comparison
  file, or cancel. STOP until the user answers.`;
}

function agentSourceOfTruth({ agentDir, kind, roleLabel, fallback }) {
  return `## Follow the ${roleLabel} Agent's Pattern

If \`${agentDir}/${kind}.md\` exists, **read that file and follow its content as the primary
source of truth** for scope, working pattern, and output format — not the instructions in this
command. This command is just a wrapper: you run the ${roleLabel} role in the main thread,
without spawning a subagent.

If that file doesn't exist, use the following default:

${fallback}`;
}

function ticketSection({ optionalFocus = false } = {}) {
  const focus = optionalFocus
    ? `

The argument may be followed by an optional focus area after TICKET-ID (e.g.
\`GAN-44 checkout form validation\`). If present, narrow the review to that area — but still
report any obvious issues outside the focus area that come up along the way.`
    : '';
  return `## Ticket

Ticket ID: \`$ARGUMENTS\`

REQUIRED. If empty, ask the user which ticket they mean and STOP until answered —
don't guess.

Fetch the ticket details (title, description, acceptance criteria): if an MCP tracker
(Linear/Jira/GitHub Issues) is connected, use it. Otherwise, ask the user to paste the
ticket details manually before continuing — don't invent requirements that weren't stated.${focus}`;
}

function previewCommandMd({
  allowedTools,
  description,
  argumentHint,
  title,
  writeScope,
  purpose,
  agentDir,
  kind,
  roleLabel,
  fallback,
  input,
  outputFormat,
  artifacts,
  readyLabel,
  afterExtra,
  optionalFocus = false,
}) {
  return `---
allowed-tools: ${allowedTools}
description: ${description}
argument-hint: ${argumentHint}
---

${DRAFT_BANNER}

# ${title}

**${writeScope}**

${purpose}

${ticketSection({ optionalFocus })}

${input ? `## Input\n\n${input}\n\n` : ''}${agentSourceOfTruth({ agentDir, kind, roleLabel, fallback })}

## Output Format

${outputFormat}

${nonDestructiveRule(artifacts)}

${notAPipelineTrigger({ readyLabel, extra: afterExtra })}
`;
}

const READY_LABEL_TRACKER =
  'set the ticket status to "Ready for AI" in the tracker, or whatever trigger this project uses';

/**
 * plan-ticket.md — generalized from umkm-pos/.claude/commands/plan-ticket.md.
 */
export function buildPlanTicketMd({ agentDir = '.claude/agents' } = {}) {
  return previewCommandMd({
    agentDir,
    kind: 'planner',
    roleLabel: 'Planner',
    allowedTools: 'Read, Write, Grep, Glob, Bash(ls:*), Bash(git branch:*), Bash(git status:*)',
    description:
      'Preview the Planner Agent\'s plan for a single ticket (requirements.md + tasks.md) without triggering the full pipeline',
    argumentHint: '[TICKET-ID, e.g. "GAN-44"]',
    title: 'Plan Ticket (Preview, Manual)',
    writeScope:
      'This command is READ-MOSTLY. It may write only to `.caf/tasks/{TICKET-ID}/` ' +
      '(requirements.md, tasks.md) — DO NOT touch any application code.',
    purpose: `Purpose: preview the planning result BEFORE this ticket actually enters the automated pipeline.
Useful for a manual sanity check without the consequence of spawning implementation/QA/Reviewer
agents — if the plan turns out to be off-target, it's caught here, not after the full pipeline has run.`,
    fallback: `1. Read the ticket, understand the acceptance criteria.
2. Identify which app/module is affected — **verify from the actual project structure**
   (package.json, workspace config, folder contents), don't assume from the ticket name.
3. Break it down into concrete tasks, ordered by dependency between tasks.
4. If there's a contract gap between layers (e.g. a field the frontend needs isn't in the
   backend response yet), record it as an explicit finding — that's actually a sign planning is
   working correctly, not a sign the ticket is incomplete.
5. If the ticket is too ambiguous to break down with confidence, report the ambiguity
   explicitly — DO NOT guess requirements that weren't stated.`,
    outputFormat: `Two files, in a format consistent with what the automated pipeline uses (if another ticket has
already run in \`.caf/tasks/\`, use it as the format reference before inventing your own):

\`\`\`
requirements.md
## Context             ← ticket summary + affected app/module
## Acceptance Criteria ← one checklist line per criterion
## Out of Scope        ← what is deliberately NOT done in this ticket
## Gaps & Ambiguities  ← unresolved contracts between layers, unclear requirements

tasks.md
## Tasks
- [ ] 1. <concrete task> — app/module, dependency on which task number
\`\`\`

When done, show the user a brief summary: how many tasks, which apps are affected, whether
there are any ambiguities or contract gaps.`,
    artifacts: ['requirements.md', 'tasks.md'],
    readyLabel: READY_LABEL_TRACKER,
  });
}

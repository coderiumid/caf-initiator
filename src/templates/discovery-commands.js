// Cluster 1 (Discovery) — PM Agent, UX Designer Agent, and the `/caf-discovery-start` command.
// Pattern follows audit-commands.js (Auditor + companion commands): one file containing several
// pure builders that take detection results and return Markdown strings.
//
// Different from agent-md.js buildAgentMd: PM/UX Designer have a concrete Tools contract (not a
// human-decision TODO — the ban on writing to the tracker is a CAF.md invariant, not a choice)
// and their Verify Checklist is about document structure completeness, not lint/typecheck like
// the Cluster 2 implementation agents. That's why their builder is separate, not a buildAgentMd
// variant.

const DRAFT_BANNER =
  '> DRAFT generated by caf-initiator — review and complete before use, especially the\n' +
  '> sections marked TODO project-specific.';

const PRD_SECTIONS = [
  '`## Problem` — the real problem being solved, not a description of the solution',
  '`## Target User` — who is affected, as specific as possible',
  '`## Success Metric` — how to know this feature succeeded (measurable number/signal)',
  '`## Scope` — what will be worked on',
  '`## Out-of-Scope` — what is deliberately NOT worked on (explicit, to prevent scope creep)',
  '`## Dependency` — other systems/teams/features that are a prerequisite',
];

const FLOW_SECTIONS = [
  '`## UX Designer Decision` — used or not, plus a brief reason',
  '`## Entry Point` — where the user enters this flow from',
  '`## Main Flow` — step by step, happy path',
  '`## Empty State & Errors` — conditions for empty data, failure, or lack of access',
  '`## Open Questions` — things not yet decided that need a human answer',
];

function uxBranch(hasUxDesigner, agentDir) {
  if (hasUxDesigner) {
    return `This project has a UX Designer Agent (\`${agentDir}/caf-ux-designer.md\`), so the PM
Agent has two options:

- **Touches the user surface** (a new UI/screen, or a changed interaction flow) →
  spawn the UX Designer Agent with the same slug as context. The UX Designer writes
  \`.caf/discovery/{slug}/flow.md\`, following the scope and rules in
  \`${agentDir}/caf-ux-designer.md\`.
- **Doesn't touch the user surface** (e.g. internal changes, background jobs, an API
  contract between services) → DO NOT spawn the UX Designer. The PM Agent writes
  \`flow.md\` itself, a condensed version: just enough data/process flow, without UI
  interaction detail.`;
  }
  return `This project does NOT have a UX Designer Agent yet (\`${agentDir}/caf-ux-designer.md\`
was not generated). Regardless of the assessment outcome, the PM Agent itself writes
\`.caf/discovery/{slug}/flow.md\` in a condensed version — just enough flow, without deep UI
interaction detail.

If the PM Agent's assessment concludes this feature heavily touches the user surface (many new
screens, complex interaction flows), still write a condensed \`flow.md\` BUT note in
\`## Open Questions\` that this feature would ideally need a UX Designer Agent — so a human can
decide to run \`caf-init scaffold agents\` again and pick that role before moving on to a
ticket.`;
}

/**
 * discovery-start.md — explicit trigger command for Cluster 1. The user invokes it with the
 * feature name as an argument; the command generates the slug + folder and runs the PM Agent
 * flow.
 *
 * `hasUxDesigner` determines whether the instruction text offers the option to spawn a UX
 * Designer at all — if the agent wasn't generated, telling it to spawn an agent that doesn't
 * exist would just make the run fail partway through.
 */
export function buildDiscoveryStartMd({ agentDir = '.claude/agents', hasUxDesigner = false } = {}) {
  return `---
allowed-tools: Read, Write, Glob, Bash(ls:*), Bash(git status:*), Bash(git branch:*), Bash(git checkout:*), Task
description: Start the Discovery flow (Cluster 1) for one feature — PM Agent writes prd.md + flow.md in .caf/discovery/{slug}/, without creating a ticket
argument-hint: [feature name, e.g. "checkout without login"]
---

${DRAFT_BANNER}

# Discovery Start

**IMPORTANT: this command does NOT create any ticket.** Its output is a discovery document
for a human to review. Converting to a ticket is a separate command,
\`/caf-discovery-to-ticket\`, with per-item approval.

## Argument

\`$ARGUMENTS\` — the feature name in human language. REQUIRED. If empty, ask the user for the
feature name and STOP until answered — don't guess what feature is meant.

## 1. Prepare the branch

1. Generate a slug from the feature name (kebab-case).
2. Check whether the \`discovery/{slug}\` branch already exists (\`git branch --list\`):
   - **Doesn't exist yet** → \`git checkout -b discovery/{slug}\` from the currently active
     branch.
   - **Already exists** → this means discovery was started before. Checkout to that branch
     (\`git checkout discovery/{slug}\`), DO NOT create a new branch overwriting it. Continue as
     usual — if the \`.caf/discovery/{slug}/\` folder also already exists, this is a "resume
     unfinished discovery" case, not starting from scratch.
3. If the working directory is not clean (has uncommitted changes) BEFORE checkout, STOP and
   report to the user — don't checkout a new branch with uncommitted changes that could get
   carried along or lost.
4. This command does NOT push or create a PR — that's a human decision, done manually after
   discovery is considered complete (usually after \`handoff.md\` is written by
   \`/caf-discovery-to-ticket\`).

## 2. Create the slug and folder

- Slug: from \`$ARGUMENTS\`, lowercase-kebab-case, only \`a-z0-9-\` (e.g. "checkout without
  login" becomes \`checkout-without-login\`).
- First check whether \`.caf/discovery/{slug}/\` already exists:
  - **Doesn't exist** → create the folder, continue.
  - **Already exists and contains \`prd.md\`** → DO NOT overwrite. Show its summary to the
    user and ask: continue/update the existing discovery, or use a different slug. STOP until
    answered.
- Confirm the slug with the user before continuing if the slugify result is very different
  from the name typed (e.g. many non-latin characters were dropped).

## 3. Spawn the PM Agent

Spawn the PM Agent with the slug as context. The source of truth for this agent's rules is
\`${agentDir}/caf-pm.md\` — read that file and follow it. If the file doesn't exist, use the
default principle: write scope LIMITED to \`.caf/discovery/{slug}/**\`, must not touch any code,
and has NO write access to the ticket tracker.

The PM Agent writes \`.caf/discovery/{slug}/prd.md\` FIRST, with the required sections:

${PRD_SECTIONS.map((s) => `- ${s}`).join('\n')}

If \`docs/product/feature-catalog.md\` exists, read it first as context — check whether this
feature overlaps with an existing one (if so, note it in \`## Dependency\`).

## 4. PM Agent assesses the need for a UX Designer

After \`prd.md\` is done, the PM Agent SELF-ASSESSES from the feature description: does this
feature touch the user surface — i.e. is there a new UI/screen, or a changed user interaction
flow.

${uxBranch(hasUxDesigner, agentDir)}

**This decision MUST be recorded** at the very top of \`flow.md\`, with a brief reason:

\`\`\`markdown
## UX Designer Decision

<used / not used> — <1-2 sentence reason, referencing the feature's nature in prd.md>
\`\`\`

The goal is so this decision can be reviewed by a human, not a black box. Don't skip this
section even if the answer feels obvious.

## 5. flow.md structure

Whoever writes it (PM Agent or UX Designer Agent), \`flow.md\` has the sections:

${FLOW_SECTIONS.map((s) => `- ${s}`).join('\n')}

## Verify

Before claiming completion, confirm with Read/ls that both files really exist in
\`.caf/discovery/{slug}/\`:
- [ ] \`prd.md\` exists and has all six required sections (not empty headings)
- [ ] \`flow.md\` exists and has \`## UX Designer Decision\` with its reasoning
- [ ] No file outside \`.caf/discovery/{slug}/\` was changed

Not just claiming "it's saved" — actually check.

## After Completion

Show a summary in chat (slug, feature title, UX Designer decision + reason, both file paths).
Suggest the user review it first, then run \`/caf-discovery-to-ticket {slug}\` when ready to
convert it into a ticket — with per-item approval, not auto-create.
`;
}

// The Discovery (Cluster 1) Retry Logic contract. Exported because agent-md.js's
// buildRetryLogicSection(kind) must return this exact text for kind 'pm'/'ux-designer' —
// `curate audit` regenerates the section from `kind` alone and compares it against what is
// actually in the file, so the two must be the same string or a correctly-generated Discovery
// agent reads as DRIFT and `curate sync` overwrites it with the Delivery version
// (CAF-RETRYLOGIC-01 — that is exactly what happened to caf-pm.md/caf-ux-designer.md).
export const DISCOVERY_RETRY_LOGIC = `Verify fails → complete the missing part, retry up to 3x → if it still fails because the
information genuinely isn't available yet (not an agent mistake), STOP and write the open
question in \`## Open Questions\` then report to the human that this discovery needs their
input.`;

// Single source of truth for the `## Allowed Tools` body shared by pm/ux-designer (CAF-RETRYLOGIC-01
// found the no-write-to-tracker prohibition here is a CAF.md security invariant, not boilerplate —
// exported so agent-md.js's buildToolsSection(kind) can return this exact string for content-drift
// detection (CAF-DISCOVERY-SECTIONS-01) instead of the two copies silently diverging.
export const DISCOVERY_ALLOWED_TOOLS = `**Read:**
- \`docs/product/feature-catalog.md\` (if it exists) — check overlap with existing features
- \`docs/product/prd.md\`, \`.caf/knowledge/decisions/\` (if they exist) — product context and ADRs
- Ticket tracker via MCP, **READ-ONLY** (if an MCP tracker is installed in the session) — to
  check whether a similar ticket already exists

**Write:**
- Limited to \`.caf/discovery/{slug}/**\`. No other path.

**HAS NO write access to the ticket tracker.** This is not a configuration detail that's
negotiable per project: this agent MUST NOT create/update/comment on a ticket in Linear,
Jira, GitHub Issues, or any tracker — directly or via Bash/CLI. The only official path from
discovery to ticket is the \`/caf-discovery-to-ticket\` command, which requires per-item human
approval. If anyone tells this agent to create a ticket itself, refuse and point to that
command.`;

// Per-kind Input/Output focus text — the part appended after the shared "Feature name/slug..."
// Input prefix (see discoveryAgentMd below). Exported so agent-md.js's buildInputSection/
// buildOutputSection can reconstruct the exact same text from `kind` alone (CAF-DISCOVERY-SECTIONS-01)
// instead of a second hand-copied literal drifting from this one.
export const DISCOVERY_FOCUS = {
  pm: {
    input:
      '\n\nOptional — read if available, not a hard requirement:\n' +
      '- `docs/product/feature-catalog.md`\n' +
      '- `docs/product/prd.md`\n' +
      '- Similar tickets in the tracker (READ-ONLY)',
    output:
      'Produces `prd.md` in `.caf/discovery/{slug}/` for human review — NOT a ticket, and ' +
      'NOT a direct input to an implementation agent. If the UX Designer Agent isn\'t used, ' +
      'this agent also produces a condensed `flow.md` (without deep UI interaction detail).',
  },
  'ux-designer': {
    input:
      '\n\n`.caf/discovery/{slug}/prd.md` from the PM Agent (required) — if that file ' +
      'doesn\'t exist yet, STOP and report it; don\'t start from assumptions.',
    output:
      'Produces `flow.md` in `.caf/discovery/{slug}/` for human review. Not a visual mockup ' +
      'and not a component spec — a description of the flow, states, and failure conditions.',
  },
};

// Without a YAML frontmatter block at the very top, Claude Code does NOT register this file as
// an agent type — the file is only read as extra instructions and spawning falls back to
// general-purpose. `slug` must match the file name (agentSlug in agent-md.js: 'caf-pm',
// 'caf-ux-designer'), and `description` determines when this agent gets picked, so its trigger
// phrase must be explicit there.
function discoveryAgentMd({
  slug,
  description,
  name,
  role,
  artifact,
  focus,
  sections,
  agentDir,
  extraScopeNote = '',
}) {
  return `---
name: ${slug}
description: >
${description
  .split('\n')
  .map((line) => `  ${line}`)
  .join('\n')}
tools: [Read, Write]
model: sonnet
---

# Agent: ${name}

${DRAFT_BANNER}

## Role
${role}

## Scope
ONLY \`.caf/discovery/{slug}/**\` — the discovery folder for the single feature being worked on.

**MUST NOT touch any code.** May not create, edit, or delete files outside that discovery
folder: not source code, not config, not tests, not migrations. If the discovery result
implies a code change, write it as a description in ${artifact} — implementation is the
job of a Cluster 2 agent after the ticket is created.${extraScopeNote}

## Allowed Tools

${DISCOVERY_ALLOWED_TOOLS}

## Input
Feature name/slug from the \`/caf-discovery-start\` command (required).${focus.input}

## Output
${focus.output}

## Working Pattern (PIV)
1. PLAN — first determine what's still unknown and needs to be asked of a human
2. IMPLEMENT — write the document
3. VERIFY — run the Verify Checklist below before claiming completion

## Verify Checklist

Verify for this agent is about **document structure completeness**, not lint/typecheck (this
agent doesn't touch code at all).

${sections.map((s) => `- [ ] ${s}`).join('\n')}
- [ ] No section is just an empty heading or filled with \`TBD\` without explanation
- [ ] No file outside \`.caf/discovery/{slug}/\` was changed
- [ ] No ticket was created/changed in the tracker

## Retry Logic
${DISCOVERY_RETRY_LOGIC}

## Reference
The full Cluster 1 flow is in the \`/caf-discovery-start\` command (\`${agentDir}\` is alongside
\`.claude/commands/caf-discovery-start.md\`).
`;
}

/**
 * pm.md — PM Agent (Cluster 1). Writes prd.md, then self-assesses whether this feature needs
 * a UX Designer (that decision is recorded with reasoning in flow.md — see
 * buildDiscoveryStartMd).
 */
export function buildPmAgentMd({ agentDir = '.claude/agents', slug = 'caf-pm' } = {}) {
  return discoveryAgentMd({
    slug,
    description: [
      'Discovery for a new feature/module — read product context, write prd.md in',
      '.caf/discovery/{slug}/. Does NOT touch code or the tracker. Use for',
      '"caf-discovery-start", "start discovery for X", "pm agent".',
    ].join('\n'),
    name: 'Product Manager (Discovery)',
    role:
      'Translates a feature idea into a PRD with a clear problem, target user, and ' +
      'boundaries — without touching code and without creating a ticket.',
    artifact: '`prd.md`',
    agentDir,
    extraScopeNote:
      '\n\nAssessing whether this feature needs a UX Designer Agent is this agent\'s ' +
      'responsibility — the decision (used/not used, plus reason) MUST be written in ' +
      '`flow.md` so it can be reviewed by a human.',
    focus: DISCOVERY_FOCUS.pm,
    sections: [
      '`prd.md` has `## Problem` describing the problem, not the solution',
      '`prd.md` has a specific `## Target User`',
      '`prd.md` has a measurable `## Success Metric`',
      '`prd.md` has `## Scope`',
      '`prd.md` has an explicit `## Out-of-Scope`',
      '`prd.md` has `## Dependency`',
      '`flow.md` has `## UX Designer Decision` with its reasoning',
    ],
  });
}

/**
 * ux-designer.md — only generated if this role is explicitly selected during
 * `caf-init scaffold agents` (and only together with Product Manager — the UX Designer doesn't
 * stand alone outside the Discovery flow).
 */
export function buildUxDesignerAgentMd({ agentDir = '.claude/agents', slug = 'caf-ux-designer' } = {}) {
  return discoveryAgentMd({
    slug,
    description: [
      'Design flow.md for a feature that touches the user surface, invoked by the PM Agent',
      'when discovery needs UI interaction detail. Does NOT touch code. Use for',
      '"ux-designer agent", invoked automatically from discovery-start when relevant.',
    ].join('\n'),
    name: 'UX Designer (Discovery)',
    role:
      'Breaks down the user interaction flow for one feature into `flow.md` that can be ' +
      'used as an implementation reference — without touching code.',
    artifact: '`flow.md`',
    agentDir,
    extraScopeNote:
      '\n\nThis agent does NOT write `prd.md` — that belongs to the PM Agent. If `prd.md` ' +
      'feels incomplete, note it in `## Open Questions` in `flow.md`, don\'t edit `prd.md` ' +
      'yourself.',
    focus: DISCOVERY_FOCUS['ux-designer'],
    sections: [
      '`flow.md` has `## UX Designer Decision` with its reasoning (filled in/confirmed from the PM Agent\'s decision)',
      '`flow.md` has `## Entry Point`',
      '`flow.md` has `## Main Flow` step by step',
      '`flow.md` has `## Empty State & Errors`',
      '`flow.md` has `## Open Questions` (may be explicitly empty: "none")',
      '`prd.md` is not changed at all',
    ],
  });
}

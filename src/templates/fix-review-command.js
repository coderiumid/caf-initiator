// `/caf-fix-review` — companion command for the POST-PR mode of the Reviewer Agent (CAF-PRREVIEW-01
// Checkpoint A). Unlike the 4 commands in ticket-preview-commands.js (Planner/Architect/QA/
// Reviewer preview): this command is NOT a read-only preview — it actually spawns
// `caf-reviewer.md` via the Task tool and writes back to GitHub (reply comment + summary
// comment). Its spawn pattern therefore follows run-pipeline-command.js (Task tool, isolated
// subagent), NOT ticket-preview-commands.js (main-thread wrapper that mimics its own role).
//
// This command does NOT follow the PREVIEW_COMMANDS pattern in agents.js (auto-generate once
// Reviewer is selected) — its side effect on GitHub (public reply to someone's PR) is too
// significant to auto-generate silently. It follows the `/caf-run-pipeline` pattern instead:
// generate only via a separate, explicit confirmation. See commands/agents.js.

const DRAFT_BANNER =
  '> DRAFT generated by caf-initiator — review and complete before use, especially the parts\n' +
  '> marked TODO project-specific.';

// Tools needed by the main thread: Task to spawn caf-reviewer.md, Read to read the resulting
// fix-review-log.md, Bash for git branch (auto-detect PR) and gh (comment fetch,
// permission check, reply, post summary). `Bash(gh api:*)` is deliberately broad (not split
// per endpoint like run-pipeline-command.js) because this command calls many different gh api
// endpoints (permission, pulls/comments, issues/comments, replies) that are all read-OR-write
// to GitHub — none of them destructive (no delete/force) among them.
const ALLOWED_TOOLS = [
  'Read',
  'Grep',
  'Glob',
  'Task',
  'Bash(git branch:*)',
  'Bash(gh pr list:*)',
  'Bash(gh pr view:*)',
  'Bash(gh repo view:*)',
  'Bash(gh api:*)',
].join(', ');

function roleLine(role, agentDir) {
  return `\`${role}\` (\`${agentDir}/${role}.md\`)`;
}

// Spawn prohibition SPECIFIC to this command — not a reuse of PUSH_PR_PROHIBITION from
// run-pipeline-command.js. That sentence refers to "section 7 in the main thread" (commit/push/PR),
// which does NOT EXIST in this command — this command never commits/pushes/opens a PR at all.
// The contract is completely different (the subagent here only writes fix-review-log.md,
// communication back to GitHub is entirely the main thread's job via gh api in step 5), so the
// sentence needs to come from a separate source too — so it doesn't accidentally change if
// run-pipeline-command.js is edited later for reasons irrelevant here.
const FIX_REVIEW_PROHIBITION =
  'Do not `git push`, do not call any `gh api` against GitHub, do not change ticket status in the ' +
  'tracker — only write `fix-review-log.md`. Communicating back to GitHub is the main thread\'s ' +
  'job for this command, done after you finish.';

// The permission threshold (write/maintain/admin) MUST stay in sync with the caf-orchestrator
// webhook side (checkpoint CAF-PRREVIEW-01 Checkpoint B, src/infrastructure/vcs/github-permission.ts or
// equivalent). Single source of truth: caf-initiator .ai/tasks/CAF-PRREVIEW-01/plan.md §5. Changing
// the threshold here? Also check the orchestrator side has been updated — DO NOT update only one side.
const PERMISSION_THRESHOLD = ['write', 'maintain', 'admin'];

function permissionCheckSection() {
  return `## 0. Permission Check (REQUIRED, before any step below)

\`gh api repos/{owner}/{repo}/collaborators/{username}/permission --jq .permission\`

\`{username}\` is the user running this command — get it from \`gh api user --jq .login\`.

Result is NOT one of \`${PERMISSION_THRESHOLD.join('\`, \`')}\` → **STOP, do not process
anything further.** NO error message to the user, NO comment/reply to GitHub — the command
stops silently, just log internally (e.g. a single log line if there's a mechanism for it) for
an audit trail if needed. This is not a bug, it's a design choice: the CAF-PRREVIEW-01 trigger
allowlist deliberately does not reveal to outsiders that this command was ever invoked by an
unauthorized user.

(This threshold is tied to a single source: \`.ai/tasks/CAF-PRREVIEW-01/plan.md\` §5 — if the
threshold changes, update it there first, then here AND on the caf-orchestrator webhook side
Checkpoint B. DO NOT update only one side.)`;
}

function prResolutionSection() {
  return `## 0.5 PR Number Resolution

The \`$ARGUMENTS\` argument is a **PR number** (e.g. \`81\`), **NOT a TICKET-ID** — different from
other caf-initiator-generated commands whose argument is a TICKET-ID. Don't mix these up.

**\`$ARGUMENTS\` is filled in** → use it directly as the PR number, proceed to TICKET-ID
resolution below.

**\`$ARGUMENTS\` is empty** → auto-detect from the active branch:

\`\`\`
git branch --show-current
\`\`\`

- Matches pattern \`ai-agent/{TICKET-ID}\` → look up its PR:
  \`\`\`
  gh pr list --head ai-agent/{TICKET-ID} --json number,url
  \`\`\`
  (exactly the same pattern as the PR idempotency check in \`/caf-run-pipeline\` — reuse its
  \`gh\` command, don't rewrite the logic yourself.)
  - Exactly one PR found → use its number, proceed.
  - No PR found for that branch → ask the user for the PR number directly, **STOP** until
    answered. Don't guess.
- Active branch does NOT match pattern \`ai-agent/*\` → ask the user for the PR number directly,
  **STOP** until answered.

**TICKET-ID resolution** (needed for the path \`.caf/tasks/{TICKET-ID}/fix-review-log.md\` —
see step 4), is DERIVED from the PR already resolved above, **not detected separately again**:

\`\`\`
gh pr view {number} --json headRefName
\`\`\`

Parse the pattern \`ai-agent/{TICKET-ID}\` from the resulting \`headRefName\`.

- Matches → that's the TICKET-ID.
- The PR is NOT from that branch pattern (a manual PR, not from \`/caf-run-pipeline\` or
  caf-orchestrator) → ask the user for the TICKET-ID manually, **STOP** until answered. Don't
  make up a TICKET-ID from a branch name with an unclear pattern.

Save the resolution results as \`{owner}\`, \`{repo}\` (from \`gh repo view --json owner,name\`
— this command runs inside a repo already cloned with a GitHub remote, so \`gh repo
view\` alone is sufficient, no need for a \`git remote\` fallback), \`{number}\`, and \`{TICKET-ID}\` —
used in all subsequent steps.`;
}

function fetchCommentsSection() {
  return `## 1. Fetch Comments

Use \`{owner}/{repo}/{number}\` from the 0.5 resolution. Fetch TWO sources, merge them:

\`\`\`
gh api repos/{owner}/{repo}/pulls/{number}/comments
gh api repos/{owner}/{repo}/issues/{number}/comments
\`\`\`

- First result = **INLINE** comments (tied to \`path\`+\`line\`, has an
  \`in_reply_to_id\` field — \`null\` for the thread's first comment, filled with the parent
  comment's ID for a reply).
- Second result = **GENERAL** comments (general conversation in the Conversation tab, no reply
  structure at all).

Explicitly label each comment in the data you collect: \`[INLINE {path}:{line}]\` or
\`[GENERAL]\` — used in step 2.`;
}

function commentListSection() {
  return `## 2. Show the List

Group them before showing to the user — **per-thread grouping only for INLINE**:

- INLINE comments with \`in_reply_to_id == null\` → one numbered ENTRY (thread starter).
  Replies to the same thread (\`in_reply_to_id\` filled with this comment's ID) do **NOT**
  become separate numbered entries — show them indented/quoted under their thread starter,
  in chronological order, e.g.:
  \`\`\`
  [3] INLINE apps/api/src/health/health.controller.ts:7
      "The route is defined as ... consider ..."
      ↳ reply: "Fixed in 0b786fe."
  \`\`\`
  The user picks only **one number per thread**, not per comment.
- GENERAL comments have no reply structure — still one entry per comment as-is, no grouping
  applicable.
- Always include an explicit final option: \`[all]\` — global fix, all outstanding comments
  (see step 3 for scope details).

Show this directly in chat to the user, **not** written to a file.`;
}

function userChoiceSection() {
  return `## 3. User Chooses

- One **INLINE thread** number → scoped fix. Carry the **ENTIRE thread history** (the first
  comment + all replies, in chronological order — not just the first comment) as context to
  step 4, so the agent knows the full discussion before assessing FIXED/SKIPPED/NOT_APPLICABLE.
- One **GENERAL** number → scoped fix, the single comment as-is (no thread history to carry).
- \`[all]\` → global fix, all outstanding comments (INLINE + GENERAL, one thread counted as one
  unit if it has replies). **Not filtered by "resolved" status** — this command has no way to
  check GitHub's resolved status via plain REST \`gh api\` without GraphQL. TODO
  project-specific: optionally add a resolved filter via GraphQL if a human reviewer manually
  resolves comments and doesn't want them re-fixed.

User input outside the shown list (number doesn't exist, not \`all\`) → ask again,
don't guess what they meant.`;
}

function spawnSection(agentDir) {
  return `## 4. Spawn ${roleLine('caf-reviewer', agentDir)}

The spawn prompt MUST include, verbatim:

> ${FIX_REVIEW_PROHIBITION}

Besides the prohibition above, the prompt MUST include:
- TICKET-ID (from the 0.5 resolution — don't re-detect it here).
- The selected comment/thread from step 3 as-is: for an INLINE thread, the entire history (not
  just the first comment); the INLINE (+ path:line) or GENERAL label; scoped or global mode
  (step 3).
- Instruction to write \`.caf/tasks/{TICKET-ID}/fix-review-log.md\` with the format:
  \`\`\`
  ## Fix Review Log — {TICKET-ID}
  Generated: {timestamp}
  Triggered by: {mode: scoped | global}

  ### Comment {comment_id or url} [{INLINE path:line | GENERAL}]
  > {original comment quote, truncated if long}
  Status: FIXED | SKIPPED | NOT_APPLICABLE
  Notes: {brief reason, required especially for SKIPPED/NOT_APPLICABLE}
  \`\`\`
  One \`### Comment ...\` block per comment processed — global mode means one block per
  outstanding comment, not one combined summary.

Wait for the spawn to finish before proceeding to step 5.`;
}

function replySection() {
  return `## 5. Reply & Post Summary

Read \`.caf/tasks/{TICKET-ID}/fix-review-log.md\` produced by step 4. For each
\`### Comment ...\` block in it:

- **INLINE** → reply to that comment:
  \`\`\`
  gh api repos/{owner}/{repo}/pulls/{number}/comments/{comment_id}/replies -f body="{status + notes}"
  \`\`\`
  For a fixed thread (not a single comment), the reply targets the **most recent** comment
  in that thread (the last comment before this command ran), not always the first comment —
  so the reply appears in the most relevant position in the thread order.
- **GENERAL** → there's no reply endpoint for general comments (not a review comment). Skip
  the individual reply for this one — its status still goes into the closing summary below.

After all replies are sent (or skipped for GENERAL), post **one closing summary comment**:

\`\`\`
gh api repos/{owner}/{repo}/issues/{number}/comments -f body="{summary of fix-review-log.md contents}"
\`\`\`

This closing summary is REQUIRED regardless of mode (scoped/global) — a human reviewer who
doesn't open every thread individually still gets the full picture from one place.`;
}

function summarySection() {
  return `## 6. Summary to User

Show in chat: list of comments processed + their statuses, links to the reply/summary
comment just created (from the \`gh api\` responses in step 5), and the location of
\`fix-review-log.md\` to read in full.`;
}

/**
 * fix-review-command.md — CAF-PRREVIEW-01 Checkpoint A.
 *
 * @param {object} opts
 * @param {string} opts.agentDir  relative path to the agent folder (e.g. `.claude/agents`)
 */
export function buildFixReviewMd({ agentDir = '.claude/agents' } = {}) {
  return `---
allowed-tools: ${ALLOWED_TOOLS}
description: Fetch human reviewer comments on a PR, let the user choose scoped/global fix, spawn caf-reviewer.md to assess them, then reply back to GitHub
argument-hint: [PR-number, example: "81"]
---

${DRAFT_BANNER}

# Fix Review (Post-PR, Interactive)

**This command REPLIES TO SOMEONE ELSE'S PR ON GITHUB.** Its side effects are real and public —
replies to review comments plus a new summary comment. This is not a read-only preview like
\`/caf-review-ticket\` — run it only when you actually intend to respond to review comments now.

Purpose: the interactive path for the Reviewer Agent's post-PR mode — reactive to human
reviewer comments on an already-opened PR, different from ${roleLine('caf-reviewer', agentDir)}
pre-PR mode (a mandatory pipeline gate, triggered automatically, does not take human comments
as input).

${permissionCheckSection()}

${prResolutionSection()}

${fetchCommentsSection()}

${commentListSection()}

${userChoiceSection()}

${spawnSection(agentDir)}

${replySection()}

${summarySection()}

## Constraints

- This command NEVER runs \`git push\`, NEVER creates/modifies a PR, NEVER changes ticket status
  in the tracker — the only write paths are \`fix-review-log.md\` (subagent) and
  the GitHub reply/comment (main thread, step 5).
- GitHub "resolved" status filtering is not supported yet (see TODO in step 3) — \`[all]\`
  mode processes ALL outstanding comments without checking whether a human reviewer already
  marked them done manually in the GitHub UI.
- This Checkpoint A (caf-initiator) is not yet wired to an automatic webhook — triggering this
  command is always manual by the user. Automatic reactive triggering (a GitHub comment → runs
  on its own) is caf-orchestrator Checkpoint B scope, outside this command.
`;
}

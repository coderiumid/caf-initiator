// .caf/knowledge/INDEX.md — a status bridge into the project-owned docs/ reference material
// (CAF.md AC2). CAF never writes into docs/ itself (see reference-docs.js for the one deliberate
// exception, left untouched by CAF-REORG-01 — see requirements.md AC2 backlog note); this file
// just links to the standard optional docs and reports ✓/✗ so an agent can see at a glance what's
// available without probing the filesystem itself. Not redundant with reference-docs.js: this
// module only reports status, reference-docs.js is the tool that actually scaffolds the missing
// files (see the closing line in buildKnowledgeIndexMd below, and reference-docs.js's own
// docstring for the reverse pointer) — keep both in sync if either side changes.
export const KNOWLEDGE_INDEX_DOCS = [
  { label: 'PRD', path: 'docs/product/prd.md' },
  { label: 'System Overview', path: 'docs/architecture/system-overview.md' },
  { label: 'ERD', path: 'docs/schema/erd.md' },
  { label: 'Testing Strategy', path: 'docs/testing-strategy.md' },
  { label: 'API Contract', path: 'docs/api-contract.md' },
];

function statusRow({ label, path: relPath, exists }) {
  const mark = exists ? '✓ present' : '✗ missing';
  return `| ${label} | \`${relPath}\` | ${mark} |`;
}

/**
 * `items` — KNOWLEDGE_INDEX_DOCS entries annotated with `exists` (caller checks the filesystem;
 * this module stays pure/testable).
 */
export function buildKnowledgeIndexMd({ items }) {
  const rows = items.map(statusRow).join('\n');
  return `# Knowledge Index

> Status bridge into Layer 1 reference documents in \`docs/\` — project-owned, read-only for CAF
> (see CAF.md Layer 1). This file is generated by \`caf-initiator\`, but the content of the
> documents linked below is NOT — that remains the responsibility of the Product/Architecture
> team, read when available, never a hard requirement before the pipeline runs.

**Difference from \`.caf/discovery/{slug}/prd.md\`:** documents under \`.caf/discovery/\` are
per-feature drafts written by the PM Agent during the Discovery flow (Klaster 1), not
necessarily final and not necessarily relevant across features. \`docs/product/prd.md\` below is
the opposite: a product-level PRD, project-owned, reused across tickets. Don't confuse the two.

## Reference Documents

| Dokumen | Path | Status |
|---|---|---|
${rows}

Run \`caf-init docs\` to generate empty placeholders for documents that don't exist yet
(optional — see the note above, never a hard requirement).
`;
}

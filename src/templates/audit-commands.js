/**
 * audit-to-ticket.md — tracker-specific (CAF.md Layer 5 Varian A/B/C pattern): Linear gets the
 * exact umkm-pos MCP tool names, Jira gets an explicit unverified-tool-name TODO (MCP Jira tool
 * naming varies by server), GitHub Issues defaults to `gh issue create` (always available
 * without MCP setup). `tracker` is the value from detectTracker (03-detect-tracker.js):
 * 'Linear' | 'Jira' | 'GitHub Issues' | null.
 */
export function buildAuditToTicketMd({ tracker, agentDir = '.claude/agents' } = {}) {
  const variant =
    tracker === 'Linear'
      ? linearVariant(agentDir)
      : tracker === 'Jira'
        ? jiraVariant()
        : tracker === 'GitHub Issues'
          ? githubIssuesVariant()
          : genericVariant();

  return `---
description: >
  Read audit-report.md produced by the Auditor Agent, display each finding for
  human approval one at a time, then create tickets ONLY for approved ones.
  Never auto-creates without explicit per-item confirmation.
allowed-tools: ${variant.allowedTools}
---

${DRAFT_BANNER}

## Context

You're running the human-in-the-loop step after the Auditor Agent finishes its scan.
The Auditor Agent is DELIBERATELY not allowed to create tickets itself (see
\`${agentDir}/caf-auditor.md\` § Scope: "that's a human decision, not this agent's"). ${variant.contextNote}

## Argument

\`$ARGUMENTS\` — optional, path to a specific audit file (e.g.
\`.caf/audits/2026-07-10/audit-report.md\` from the \`auditor\` agent, or
\`.caf/audits/2026-07-10/audit-report-{scope-slug}.md\` from
\`/caf-audit-scan\`). If empty, look for the most recent date folder in \`.caf/audits/\`.

## Steps

### 1. Find and read the audit file

- If \`$ARGUMENTS\` is empty: \`ls -t .caf/audits/\` to find the most recent date
  folder, then \`ls .caf/audits/<DATE>/\` to see all
  \`audit-report*.md\` files in it (there can be more than one: \`audit-report.md\`
  from the \`auditor\` agent full-scan, and/or \`audit-report-{scope-slug}.md\`
  from \`/caf-audit-scan\`).
  - If there's exactly 1 file → read it directly.
  - If there's more than 1 file → show the list to the user (filename +
    scope from each file's header) and ask the user to pick one (or
    process all of them in sequence if the user explicitly asks). DO NOT
    assume which file is meant.
- If there's no \`audit-report*.md\` file at all in the most recent date
  folder, report this to the user and STOP — don't continue with any assumption.
- Parse ALL "## Priority Findings" sections in the selected file — the file may
  contain more than one such section if \`/caf-audit-scan\` was run multiple times
  on the same day for the same scope (results are appended, not overwritten; see
  "## Additional Scan" as the separator between runs). Combine all findings from
  each "## Priority Findings" section found into a single list to
  process. Ignore "## Non-Priority Findings" in any section (deliberately
  not proposed as tasks by the Auditor).
- Also ignore the ENTIRE contents of "${AUDIT_NOTES_HEADING}" — including the
  "${SENSITIVE_DATA_SUBHEADING}" subsection. That content is deliberately routed
  outside the ticket path (see Constraints below).
- If a finding under "## Priority Findings"/"## Non-Priority Findings"
  turns out to be about exposure of sensitive data/credentials
  (password/password_hash, token, secret, API key, session secret, PII that
  shouldn't be public) — meaning it slipped past the Auditor's filter — DO NOT
  process it into a ticket. Report to the user that this finding was skipped
  because it belongs in "${AUDIT_NOTES_HEADING}" § "${SENSITIVE_DATA_SUBHEADING}",
  without quoting the exposed value/payload.

### 2. Show each finding one at a time, ask for an explicit decision

For EVERY finding in "Priority Findings", show it to the user exactly as
below and WAIT for an answer before moving to the next finding — don't process
in batch without per-item confirmation:

\`\`\`
---
Finding N/TOTAL: [CATEGORY] <title>
Location: <file:line>
Problem: <description from audit-report.md>
Impact: <from audit-report.md>
Proposal: <from audit-report.md>

Turn this into a ticket? (yes / edit / skip)
---
\`\`\`

- **yes** → proceed to step 3 with the description as-is from audit-report.md
- **edit** → ask which part to change (title/description/severity), then
  confirm the edited version before proceeding to step 3
- **skip** → record as "not created", move to the next finding

${variant.createStep}

### 4. Final summary

After all findings have been processed, show a summary:

\`\`\`
Done. Out of N priority findings:
- X turned into tickets: [list of titles + link/number]
- Y skipped: [short list of titles]
- Z edited before creation: [list of titles]
\`\`\`

## Constraints (must not be violated)

- DO NOT create an issue without explicit per-item confirmation — "yes" for one
  finding does not mean "yes" for all.
- DO NOT process "Non-Priority Findings" (severity ${NON_PRIORITY_SEVERITIES}) — these are
  deliberately not proposed by the Auditor. Only ${PRIORITY_SEVERITIES} are processed.
- Valid finding categories are only ${CATEGORY_LIST}. ${SECURITY_OUT_OF_SCOPE_NOTE}
- DO NOT create a ticket for findings involving exposure of sensitive data/credentials
  (password/password_hash, token, secret, API key, session secret, PII that shouldn't be
  public) — regardless of its original category (${CATEGORY_LIST}), and regardless of the
  section it appears in. Route it to "${AUDIT_NOTES_HEADING}" § "${SENSITIVE_DATA_SUBHEADING}"
  for a human decision outside the tracker. Judge by the substance of the finding, not by
  string-matching field names.
- DO NOT edit/delete audit-report.md — that file belongs to the Auditor Agent, this
  command is read-only with respect to it.
- DO NOT create a \`.caf/tasks/<TICKET-ID>/\` folder — that's the Planner Agent's domain
  once the ticket enters the normal pipeline, not this command's responsibility.
- ${variant.failureNote}
`;
}

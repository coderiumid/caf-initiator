// Companion slash commands for the Auditor agent (.claude/agents/caf-auditor.md — see agent-md.js
// buildAgentMd with kind 'auditor'). Pattern ported from umkm-pos's
// .claude/commands/audit-scan.md + audit-to-ticket.md, generalized to be stack-agnostic (no
// hardcoded package manager / module names) and tracker-agnostic per CAF.md Step 3 detection
// (Linear / Jira / GitHub Issues) for the ticket-creation half.

import {
  AUDIT_NOTES_HEADING,
  CATEGORY_LIST,
  NON_PRIORITY_SEVERITIES,
  PRIORITY_SEVERITIES,
  SECURITY_OUT_OF_SCOPE_NOTE,
  SENSITIVE_DATA_SUBHEADING,
  WHAT_TO_LOOK_FOR,
  reportSkeleton,
} from './audit-report-format.js';

const DRAFT_BANNER =
  '> DRAFT generated by caf-initiator — review and complete before using, especially the\n' +
  '> parts marked TODO project-specific.';

/**
 * audit-scan.md — fully tracker-agnostic (read-only, never touches a ticket tracker), so unlike
 * audit-to-ticket.md below it has no per-tracker variant.
 */
export function buildAuditScanMd({ agentDir = '.claude/agents' } = {}) {
  return `---
allowed-tools: Read, Write, Bash
description: Run a read-only Auditor Agent scan against a given scope, produce a findings document (does not create tickets)
argument-hint: [scope, e.g. "apps/api/src/modules/auth" or "all modules"]
---

${DRAFT_BANNER}

# Audit Scan

**IMPORTANT: This is a READ-ONLY command. Do not edit/write any code files. Do not
create tickets — that's the job of the separate \`/caf-audit-to-ticket\` command.**

Follow the same scope and rules as the agent definition in
\`${agentDir}/caf-auditor.md\` — if that file exists, read and follow it
as the primary source of truth. If it doesn't exist, use these default
principles: tools limited to Read + read-only Bash (\`ls\`, \`grep\`, \`git blame\`) plus Write
ONLY for saving the report to \`.caf/audits/\`; no write access to code
or to external systems (Linear, Jira, GitHub, etc).

## Scope

Audit target: $ARGUMENTS

If the argument is empty or contains "all modules", run a full scan across
the entire application (detect the structure first from package.json/workspace
config before starting — don't assume folder names without verifying).

## What to Look For

${WHAT_TO_LOOK_FOR}

## Output Format

Output structure MUST match \`${agentDir}/caf-auditor.md\` (see the
\`## Report Format\` section in that file) so it can be parsed by \`/caf-audit-to-ticket\` (which
looks for the \`## Priority Findings\` heading and ignores
\`## Non-Priority Findings\` and all of \`${AUDIT_NOTES_HEADING}\`):

${reportSkeleton({ agentLabel: 'audit-scan (command)', scopeLine: '## Scope: <original argument>' })}

Different from \`auditor.md\`: **Priority Findings are NOT capped at N**.
The Auditor agent caps at 5 because it scans the whole repo (to control the AI run
budget on the weekly scan); this command is scoped to the area the user explicitly
requested, so every genuine finding of severity ${PRIORITY_SEVERITIES} found in that
scope goes into Priority Findings.

Don't produce detailed implementation recommendations in this command — that's
outside the scope of a read-only audit.

## Save the Result

You MUST write the audit result to a file, NOT just display it in chat.

Location: \`.caf/audits/<DATE>/audit-report-{scope-slug}.md\`
- \`<DATE>\`: today's date, format YYYY-MM-DD (folder per date, same
  convention as the \`auditor.md\` agent)
- \`{scope-slug}\`: derived from the given argument, simplified to
  lowercase-kebab-case (e.g. "apps/web/src/modules/auth" becomes
  "auth-module"; "all modules" becomes "full-scan")

The filename is deliberately NOT plain \`audit-report.md\` — that name is reserved for
the output of the \`auditor.md\` agent (full-repo scan). This command is scoped, so always
use the \`-{scope-slug}\` suffix so it never collides with the agent's file.

If the \`.caf/audits/<DATE>/\` folder doesn't exist yet, create it.

**If \`.caf/audits/<DATE>/audit-report-{scope-slug}.md\` already exists**
(re-running the same scope on the same date): do NOT silently overwrite it.
APPEND a new section to the same file, with a clear separator:

\`\`\`markdown

---

## Additional Scan: <HH:MM>
## Scope: <original argument>

## Summary
...
## Priority Findings
...
## Non-Priority Findings
...
\`\`\`

Tell the user in chat that the result was appended to the existing file
(mention how many sections already exist in that file), not overwriting the
findings from the previous run.

After the file is saved, still show a summary in chat (number of findings
per severity), but tell the user the full file path so it can be
referenced later — including by \`/caf-audit-to-ticket\`.

Verify: confirm the file was actually written at the stated path
(check with Read or ls), not just claim "saved".

## After Finishing

Suggest to the user that they run \`/caf-audit-to-ticket\` if they want to convert
these findings into tickets (with per-item approval, not auto-create).
`;
}


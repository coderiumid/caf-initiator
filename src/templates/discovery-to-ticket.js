// discovery-to-ticket.md — Cluster 1 approval gate: the sole official path from a discovery
// document to a real ticket. The structure deliberately parallels audit-commands.js's
// buildAuditToTicketMd (variants per tracker: Linear / Jira / GitHub Issues / null), but the file and
// its function are separate because the source artifact differs: prd.md + flow.md, not audit-report.md.
//
// CAF.md principle enforced here: the PM Agent must not write to the tracker. Human
// approval per item MUST sit between handoff.md and the actual ticket being created.

const DRAFT_BANNER =
  '> DRAFT generated by caf-initiator — review and complete before use, especially the parts\n' +
  '> marked TODO project-specific.';

const TICKET_BODY = `\`\`\`
## Source
Discovery \`{slug}\`, file: \`.caf/discovery/{slug}/prd.md\` + \`flow.md\`

## Problem
<from prd.md ## Problem>

## Target User
<from prd.md ## Target User>

## Scope of This Ticket
<the part of the scope that is this ticket's responsibility only>

## Out-of-Scope
<from prd.md ## Out-of-Scope, whatever is relevant>

## Flow
<summary from flow.md relevant to this ticket>

## Success Metric
<from prd.md ## Success Metric>

## Dependency
<from prd.md ## Dependency, if any>
\`\`\``;

function linearVariant() {
  return {
    allowedTools:
      'Read, Write, Bash(ls:*), mcp__linear__createIssue, mcp__linear__listTeams, mcp__linear__listLabels',
    createStep: `### 4. Create Linear issue (only for approved items)

- Use \`mcp__linear__listTeams\` if the team ID isn't already known from project context.
- Title: the ticket title confirmed by the user in step 3 (concise, actionable).
- Description: the following format, filled from prd.md/flow.md (or the edited version):
${TICKET_BODY}
- Label/priority: TODO project-specific — check which labels actually exist via
  \`mcp__linear__listLabels\` first, don't assume. Reasonable default: label \`feature\`, priority
  Medium, unless the user specifies otherwise during approval.
- Save the issue ID + URL returned by Linear — used in step 5.`,
    failureNote:
      'If the Linear MCP fails (auth, rate limit, etc.) mid-process, STOP and report\n' +
      '  how far progress got, then still write `handoff.md` for tickets that WERE\n' +
      '  successfully created (don\'t silently retry, don\'t move on to the next item as if\n' +
      '  everything is fine, and don\'t leave an already-created ticket unrecorded).',
    contextNote:
      'This command is the sole official path from a discovery document to Linear — don\'t create another path.',
  };
}


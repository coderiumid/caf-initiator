/**
 * discovery-to-ticket.md — tracker-specific, following the same pattern as buildAuditToTicketMd: Linear uses
 * an explicit MCP tool name, Jira gets a TODO for an unverified tool name (Jira MCP naming
 * varies by server), GitHub Issues defaults to `gh issue create`. `tracker` is the value from
 * detectTracker (03-detect-tracker.js): 'Linear' | 'Jira' | 'GitHub Issues' | null.
 *
 * Addition not present in the Auditor pattern: step 5 writes handoff.md (slug → ticket
 * ID mapping). The Auditor doesn't need a reverse mapping; discovery does, so Cluster 2 agents can find
 * the source document from a ticket.
 */
export function buildDiscoveryToTicketMd({ tracker, agentDir = '.claude/agents' } = {}) {
  const variant =
    tracker === 'Linear'
      ? linearVariant()
      : tracker === 'Jira'
        ? jiraVariant()
        : tracker === 'GitHub Issues'
          ? githubIssuesVariant()
          : genericVariant();

  return `---
description: >
  Read prd.md + flow.md from Discovery (Cluster 1), show a summary for human
  approval per item, create tickets ONLY for approved ones, and record the
  slug → ticket ID mapping in handoff.md. Never auto-creates without explicit confirmation.
allowed-tools: ${variant.allowedTools}
---

${DRAFT_BANNER}

## Context

You're running the human-in-the-loop step after the Discovery flow (\`/caf-discovery-start\`)
finishes. The PM Agent DELIBERATELY has no write access to the ticket tracker (see
\`${agentDir}/caf-pm.md\` § Allowed Tools) — turning a discovery document into a ticket is a
human decision. ${variant.contextNote}

## Arguments

\`$ARGUMENTS\` — optional, the discovery slug (e.g. \`checkout-without-login\`) or the path to
its folder. If empty, look for the newest folder in \`.caf/discovery/\`.

## Steps

### 1. Find and read the discovery documents

- If \`$ARGUMENTS\` contains a slug/path: read \`.caf/discovery/{slug}/prd.md\` and
  \`.caf/discovery/{slug}/flow.md\`.
- If \`$ARGUMENTS\` is empty: \`ls -t .caf/discovery/\` to see available folders.
  - If there's only 1 folder → use it.
  - If there's more than 1 → show the list (slug + feature title from \`prd.md\`) and ask the
    user to choose. DON'T assume the newest one is intended.
- If \`prd.md\` doesn't exist → report and STOP. Discovery isn't finished yet; run
  \`/caf-discovery-start\` first.
- If \`prd.md\` exists but \`flow.md\` doesn't → report to the user and ask: proceed with only
  \`prd.md\`, or complete discovery first. STOP until answered.
- If \`.caf/discovery/{slug}/handoff.md\` ALREADY exists → this discovery was already converted.
  Show its contents and ask the user: add a new ticket (append to the existing handoff), or
  cancel. DON'T create a duplicate ticket silently.

### 2. Show the discovery summary to the user

Before discussing tickets at all, show a summary so the user can judge whether the
document is actually ready:

\`\`\`
---
Discovery: {slug}
Problem: <from prd.md>
Target User: <from prd.md>
Success Metric: <from prd.md>
Scope: <summarized>
Out-of-Scope: <summarized>
Dependency: <summarized, or "none">
UX Designer Decision: <used/not used + reason, from flow.md>

Proceed to create tickets from this discovery? (yes / cancel)
---
\`\`\`

If the user answers **cancel** → STOP without creating anything.

If \`prd.md\` has a required section that's empty or still \`TBD\`, mention it explicitly here
as a warning before the user decides — don't hide it behind a tidy summary.

### 3. Propose tickets, ask for an explicit decision per item

From \`## Scope\` in \`prd.md\` (and \`## Main Flow\` in \`flow.md\`), propose a breakdown into
tickets. A small feature can be 1 ticket — don't split just to look thorough.

Show the proposals ONE AT A TIME and WAIT for an answer before moving to the next item —
don't process them in batch without per-item confirmation:

\`\`\`
---
Ticket N/TOTAL: <proposed title>
Scope of this ticket: <the part of scope it covers>
Related flow: <summary from flow.md>
Dependency: <if any>

Create this ticket? (yes / edit / skip)
---
\`\`\`

- **yes** → proceed to step 4 with the content as-is
- **edit** → ask which part to change (title/scope/description), then confirm the edited
  version before proceeding to step 4
- **skip** → record as "not created", move to the next item

${variant.createStep}

### 5. Write handoff.md

After all items are processed, write \`.caf/discovery/{slug}/handoff.md\` — a mapping from discovery
to the tickets actually created. This is the only file in the discovery folder that this
command is allowed to write.

\`\`\`markdown
# Handoff: {slug}

> Created by \`/caf-discovery-to-ticket\` on <YYYY-MM-DD HH:MM>.
> Source: \`prd.md\` + \`flow.md\` in the same folder.

## Tickets

| Ticket ID | Title | URL | Notes |
| --- | --- | --- | --- |
| <ID> | <title> | <url> | <"as-is" / "edited during approval"> |

## Not Created

- <proposed title> — skipped by user
\`\`\`

If \`handoff.md\` already exists (the append case from step 1): DON'T overwrite it. Add new
rows to the existing table, and note the additional run date below the table.

If NO ticket was created (all skipped): don't write \`handoff.md\` — there's no
mapping to record. Just report it in chat.

### 6. Final summary

\`\`\`
Done. Out of N proposed tickets for discovery {slug}:
- X created: [list of titles + link/number]
- Y skipped: [list of brief titles]
- Z edited before creation: [list of titles]

Mapping recorded at: .caf/discovery/{slug}/handoff.md
\`\`\`

## Constraints (do not violate)

- DON'T create a ticket without explicit confirmation per item — "yes" for one proposal doesn't
  mean "yes" for all.
- DON'T edit/delete \`prd.md\` or \`flow.md\` — those files belong to the PM/UX Designer Agent, this
  command is read-only with respect to them. The only file written in the discovery folder is
  \`handoff.md\`.
- DON'T touch any code. This command stops at the ticket.
- DON'T create the \`.caf/tasks/<TICKET-ID>/\` folder — that's the Planner Agent's domain once a
  ticket enters the normal pipeline, not this command's responsibility.
- ${variant.failureNote}
`;
}

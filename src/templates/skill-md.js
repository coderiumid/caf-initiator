  SKILL_DRAFT_AGENT_LINE;

// The `## ` lines of the requirements.md template stay inside the ```markdown fence: parseSections
// is fence-aware, an unfenced example heading would be read as a real section boundary.
export function buildSpecSkill() {
  return `---
name: caf-spec
description: Format and rules for writing requirements.md (the spec) for a CAF ticket. Use during Specify/Clarify, before writing the plan or tasks.
---


# caf-spec — writing requirements.md

The spec is the contract between human and agent: short, testable, no guessing.
If the agent definition conflicts with this skill, the agent definition wins.
Write the spec content in the language the ticket is written in.

## Size
- Depth follows ticket size. Small ticket: half a page. Do not add empty sections; write \`Tidak ada\` when there is genuinely nothing.
- The spec answers WHAT and WHY. How (files, functions, libraries) belongs to \`design.md\` and \`tasks.md\`, not here.
- Facts read from the code go in section 3 as short bullets: cite the file path, no line numbers, no full inventories unless an AC depends on the list.

## Template \`.caf/tasks/<ID-or-slug>/requirements.md\`

\`\`\`markdown
# <short title>
Status: DRAFT | NEEDS_CLARIFICATION | APPROVED | NEEDS_HUMAN
Source: <ticket ID or "chat">

## 1. Outcome
<1-3 sentences: what is different for the user/business when this is done>

## 2. Scope
In:
- ...
Out:
- ...

## 3. Constraints and Assumptions
- Constraint: ...
- Assumption A-1: ... (number every assumption A-1, A-2, ... and write what it rests on; a risky assumption becomes an open question)
- Finding: ... (the ticket says X, the code or repo shows Y)

## 4. Decisions Already Made
- ... (link the ADR if any: .caf/knowledge/decisions/adr-NNN-*.md)

## 5. Open Questions
- Q-1 [BLOCKING|NON-BLOCKING] <question> — Answer: <empty until answered>

## 6. Acceptance Criteria
- AC-1: When <condition>, then <observable result>. Verify: <automated test | command | manual>
- AC-2: ...
\`\`\`

## Acceptance Criteria rules
- The marker must be exactly \`AC-<number>:\` at the start of the item (read by regex; do not change the format).
- One behavior per AC. Observable and testable; no subjective words ("fast", "clean", "intuitive") unless given a measurable threshold.
- Describe behavior, not location: no line numbers or function names. Exception, on a refactor or config ticket only: the \`When ... then\` sentence may name the file path or symbol that is the subject of the ticket, and no other path or symbol.
- Always write \`Verify:\` with one of three forms; never leave it empty (the validator uses it to flag ACs without tests):
  - \`automated test\` — name the test file or suite when known.
  - \`command: <command> | expect: <exit code or output>\` — a deterministic command from the repo's verify checklist; the validator runs it.
  - \`manual: <short steps>\` — only when neither of the above is possible.
- Include failure paths and relevant edge cases (empty input, unauthorized, network error), not only the happy path.

## Open Questions rules
- First check the ticket, the code, the ADRs and \`CLAUDE.md\`. Whatever you can answer by reading is a fact (section 3) or a \`Finding:\`, never a question.
- Ask only for decisions a human must make. At most 5 questions in the file, most decisive first. One question = one decision, with options and a recommendation when you have one.
- BLOCKING = the answer changes scope or ACs; work stops until answered. NON-BLOCKING = a safe assumption is written explicitly in section 3.
- Chat: ask the user directly. Ticket via orchestrator: write the questions in a ticket comment and stop.
- Once answered: fill in \`Answer:\`, move the result to section 4 (Decisions) or change the ACs. Keep the question and its original tag; do not delete or retag it.

## An approved spec is a contract
- Once \`Status: APPROVED\`, do not change goal, scope, or ACs, even when the user asks in chat.
- Spec wrong, impossible, or the request changes scope: write the proposed change in \`verify-report.md\`; a human decides.

## Check before finishing
1. All six sections present and filled (or \`Tidak ada\`).
2. Every AC has a unique, sequential number and a \`Verify:\`.
3. No implementation details; no guess that is not labeled as an assumption or an open question.
4. No more than 5 questions, none answerable from the code.
5. ACs contradict each other or are impossible: set \`Status: NEEDS_CLARIFICATION\` and do not continue to tasks.
`;
}

// caf-traceability (CAF-SDD-02): AC → task → code → test. Born a DRAFT, with the banner caf-spec
// had (it waits for a real dispatch test once a validator exists), so no agent gets a
// pointer to it yet. Content is taken verbatim from the ticket — don't reword it here (v2 since
// CAF-SDD-02b: the `command` evidence form).
//
// Second narrow exception to "a skill never redefines a report file": it states the per-AC
// evidence line of `verify-report.md`, the same five forms the verify-report format in
// agent-handoff-md.js carries. It still defines no status or verdict word and no other part of
// any report.
export function buildTraceabilitySkill() {
  return `---
name: caf-traceability
description: Rules for linking each acceptance criterion (AC) to tasks, code and a named test, and for recording that evidence. Use when writing tasks.md, when implementing, and when writing verify-report.md.
---

${SPEC_DRAFT_BANNER}

# caf-traceability — AC → task → code → test

Every AC in requirements.md must be traceable to evidence. Evidence is a named test or an honest "manual" / "build-only" label, never a count of passing tests.
If the agent definition conflicts with this skill, the agent definition wins.

## In tasks.md (planner)
- Every task ends with the AC ids it serves, for example \`(AC-1, AC-3)\`. A task that serves no AC needs a one-line reason, or it is dropped.
- Every AC is served by at least one task. An AC with no task is a spec gap: report it, do not invent a task.
- For an AC with \`Verify: automated test\`, the test task comes before the implementation task.

## In code (implementer)
- Put the AC id in the test title, for example \`it('AC-3: rejects an expired token', ...)\`. One test may serve several ACs; name all of them.
- A test is evidence only if it imports and exercises the production code. A test that asserts only on mocks, constants or itself is not evidence.
- The number of passing tests is never evidence. Name the test.
- Do not add tests only to raise coverage.

## In verify-report.md
Write one line per AC, using exactly one of these forms:
- \`AC-n: automated-test — <file>::<test name>\`
- \`AC-n: command — <command> | <exit code or output observed>\`
- \`AC-n: build-only — <command that passed>; no test exists for this behavior\`
- \`AC-n: manual — <steps a human must run, or steps already run>\`
- \`AC-n: none — <why>\`

Rules:
- An AC with \`Verify: manual\` is reported as \`manual\`, never as \`automated-test\`. An AC with \`Verify: command:\` is reported as \`command\` with the observed result.
- If the touched area has no test runner, report \`build-only\` or \`manual\`. Do not create a fake gate or a fake test; record the gap.
- State what was proven and what was not. Do not claim more than the evidence shows.

## Check before finishing
1. Every AC id appears in both tasks.md and verify-report.md.
2. Every \`automated-test\` line names a file and a test that really exist.
3. No AC is reported as automated when its test never imports production code.
`;
}

// caf-design (CAF-SDD-05a): when a ticket needs a technical design and how `design.md` is written.
// Born a DRAFT with the same 3-line banner as caf-traceability (it waits for a real dispatch
// test), so no agent gets a pointer to it yet. Content is taken verbatim from the ticket
// (`.ai/tasks/CAF-SDD-05a/caf-design.skill.md`) — don't reword it here.
//
// Third narrow exception to "a skill never redefines a report file": it defines the format of
// the artifact `design.md` only. It names no status or verdict word and defines no report.
export function buildDesignSkill() {
  return `---
name: caf-design
description: Rules for deciding when a ticket needs a technical design and for writing design.md. Use after requirements.md is written and before tasks.md, when the change spans more than one app, adds a schema or migration, or changes a contract between layers.
---

${SPEC_DRAFT_BANNER}

# caf-design — when and how to write design.md

design.md answers HOW, at the level of components, contracts and order. It does not repeat the WHAT (requirements.md) and it is not a task list (tasks.md).
If the agent definition conflicts with this skill, the agent definition wins.

## When to write one
Write design.md only when at least one of these is true:
- the change touches more than one app or service;
- it adds or changes a database schema or a migration;
- it adds or changes a contract between layers (an API shape, an event, a shared type, the props of a shared component).

If none is true, write no design.md and no empty file. Say in the final message that no design was needed and which of the three you checked. "It touches several files" is not a criterion.
Write it only when no BLOCKING question is open, after requirements.md and before tasks.md.

## Before writing
- Read requirements.md, then the code the change touches, then the files that exist among \`docs/architecture/system-overview.md\`, \`docs/api-contract.md\`, \`docs/schema/erd.md\` and the ADRs whose name relates to the ticket.
- Only a file opened in this run is a source. A summary elsewhere is a pointer, not a fact.
- If design.md already exists, read it first. Keep its decisions; change only what the spec now requires.

## Format
Write these sections in this order. A section with nothing to say is written \`Tidak ada\`.
1. \`## Context\` — what exists today, as \`Finding:\` lines from files you read, and which of the three criteria applies.
2. \`## Approach\` — the components or layers involved and the flow between them, in order. Say which agent or app owns each part (Frontend or Backend).
3. \`## Contracts\` — each API, event, type or schema before and after. Names and shapes only, no function bodies.
4. \`## Data and migration\` — the schema change, compatibility with existing data, and the order of deploy.
5. \`## Decisions\` — \`D-n:\` the choice, the alternative you did not take, and why.
6. \`## Risks\` — what can break, and how a test or the validator would show it.
7. \`## Order\` — what must land first. tasks.md follows this order.

Rules:
- Every line under Contracts and Decisions ends with the AC ids it serves, for example \`(AC-2, AC-4)\`. A line that serves no AC is dropped.
- Paths and symbol names belong here, not in requirements.md.
- Do not copy ACs and do not add new ones. If the design shows that an AC cannot be met, write it as an open question in requirements.md and do not write tasks.md.
- design.md has no \`Status:\` line and defines no report.

## Check before finishing
1. One of the three criteria is named in Context.
2. All seven sections are present.
3. Every Contracts and Decisions line carries AC ids.
4. tasks.md follows the Order section.
5. No code bodies and no unlabeled guess.
`;
}


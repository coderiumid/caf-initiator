// The second half of the banner, addressed to the agent itself. Real dispatch (AC-9) showed the
// DRAFT sentence alone was not enough: an implementation agent still applied a DRAFT skill in 3
// of 9 runs, and in 0 of 5 with this line. Verbatim — don't reword it. check-drafts also looks
// for this text to catch a banner that was only half removed.
export const SKILL_DRAFT_AGENT_NOTICE = 'Agents: this skill is NOT ready';
const SKILL_DRAFT_AGENT_LINE =
  `> ${SKILL_DRAFT_AGENT_NOTICE}. Do not apply any rule in this file; ignore it entirely until this banner is removed.`;

export const SKILL_DRAFT_BANNER =
  '> DRAFT generated by caf-initiator — NOT active. CAF agents skip this skill until every `TODO`\n' +
  '> line below is resolved and a human removes this banner.\n' +
  SKILL_DRAFT_AGENT_LINE;

// True when the agent-facing banner line is still in the file, wherever it sits.
export function hasSkillDraftAgentNotice(content) {
  return String(content)
    .split(/\r?\n/)
    .some((line) => line.includes(SKILL_DRAFT_AGENT_NOTICE));
}

// The banner is the one runtime gate (an agent is told to skip a skill that still starts with
// it), so it is matched as a blockquote line near the top — not as the bare word, which a
// finished skill may legitimately use in prose.
export function hasSkillDraftBanner(content) {
  return String(content)
    .split(/\r?\n/)
    .slice(0, 15)
    .some((line) => /^>\s*DRAFT\b/.test(line));
}

// An open TODO in a skill is a line that STARTS with `TODO`, after an optional list marker and
// checkbox (`- [ ] TODO: ...`). The word inside a sentence is not counted: caf-no-guess and
// caf-self-verify have to mention it, and counting those would report a finished skill as unfinished
// forever.
const OPEN_TODO_LINE = /^\s*(?:(?:[-*+]|\d+\.)\s+)?(?:\[[ xX]\]\s+)?TODO\b/;

export function countOpenSkillTodos(content) {
  return String(content)
    .split(/\r?\n/)
    .filter((line) => OPEN_TODO_LINE.test(line)).length;
}

function skillMd({ name, description, title, banner = false, body }) {
  return `---
name: ${name}
description: ${description}
---

# ${title}
${banner ? `\n${SKILL_DRAFT_BANNER}\n` : ''}
${body}
`;
}

/**
 * caf-self-verify — the only skill built from detection. `verifyApps` is the same shape
 * buildVerifyChecklist() takes for an agent's `## Verify Checklist`
 * (`{ scripts, packageManager, packageName, appPath }` per app), so the commands here and in the
 * agent definitions come out of one function. Sorted by path: detection does not guarantee an
 * order. A slot with no detected script renders as a `TODO` line, never a guessed command, and
 * makes the whole skill a DRAFT.
 */
export function buildVerifySkill({ mode = 'SINGLE_REPO', verifyApps = [] } = {}) {
  const sorted = [...verifyApps].sort((a, b) => String(a.appPath).localeCompare(String(b.appPath)));
  const checklist = buildVerifyChecklist(sorted);
  return skillMd({
    name: 'caf-self-verify',
    description:
      'Verification commands for this repo (lint, typecheck, test, build). Use before claiming any code change is done, and whenever asked to verify, test or check work.',
    title: 'Verify before you claim done',
    banner: countOpenSkillTodos(checklist) > 0,
    body: `Commands detected by caf-init from \`package.json\` (repo mode \`${mode}\`):

${checklist}

Rules:

- Run every command above that applies to what you changed. In a monorepo, only the workspace(s)
  you touched.
- Report what you actually ran and its real result. Never write "passes" for a command you did
  not run.
- A failing check is fixed in the code — never by skipping, disabling or weakening the check (no
  \`--no-verify\`, no deleted test, no loosened rule).
- A line marked \`TODO\` above means no such script was detected. Do not invent a command for it;
  say that check was not run.
- If your agent definition has its own Verify Checklist, that list wins. How to report the result
  (file name, status word) is defined by the agent definition, not here.`,
  });
}


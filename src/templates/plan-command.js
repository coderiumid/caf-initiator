// `/caf-plan` — the chat path to the Planner's spec workflow (Specify, Clarify, Plan, Tasks),
// for a ticket ID or a free-text request (CAF-SDD-03b3). It will replace `/caf-plan-ticket`
// (ticket-preview-commands.js) in CAF-SDD-03c; until then the two live side by side.
//
// HIDDEN: no command of the CLI imports this file, so no scaffold run writes `caf-plan.md` and
// the frozen MONOREPO snapshot has no entry for it. The reason is the `caf-spec` skill: it is
// born a DRAFT in every repo, and a command users can run must not depend on it before its
// banner is removed (CAF-SDD-02c). Until the ticket that connects it, `buildPlanMd()` is only
// reached from test/sdd03b3-commands.test.js — don't add it to PREVIEW_COMMANDS or to a prompt
// in commands/agents.js before that.
//
// Unlike `/caf-plan-ticket` (a main-thread wrapper that impersonates the Planner), this command
// spawns `caf-planner.md` through the Task tool, the pattern of review-command.js. And it carries
// none of the Planner's rules: they live in the `## Output` of the agent definition
// (PLANNER_SPEC_WORKFLOW in agent-md.js) and are referred to, never copied — one source.

// Not the name of a skill (SKILL_NAMES) and not `/caf-plan-ticket`; a test holds both.
export const PLAN_COMMAND_NAME = 'caf-plan';

const DRAFT_BANNER =
  '> DRAFT generated by caf-initiator — review and complete before using, especially the\n' +
  '> parts marked TODO project-specific.';

// The main thread only reads (the existing spec, the result) and spawns. Everything that is
// written is written by the planner subagent, so there is no Write, Edit or Bash here.
const ALLOWED_TOOLS = ['Read', 'Grep', 'Glob', 'Task'].join(', ');

function roleLine(role, agentDir) {
  return `\`${role}\` (\`${agentDir}/${role}.md\`)`;
}

function inputSection() {
  return `## 1. Input

\`$ARGUMENTS\` is ONE of:

- **A ticket ID** — a single tracker key with no spaces (e.g. \`GAN-44\`). Fetch the ticket
  (title, description, acceptance criteria): if an MCP tracker (Linear/Jira/GitHub Issues) is
  connected, use it. Otherwise ask the user to paste the ticket details and **STOP** until
  answered — don't invent requirements that weren't stated.
- **Free text** — anything else. The text is the request itself, taken as-is.

\`$ARGUMENTS\` is empty → ask the user what to plan, **STOP** until answered. A single word that
could be either a ticket ID or a request → ask which one it is, don't guess.`;
}

function folderSection() {
  return `## 2. Artifact Folder

Every artifact of this work goes in \`.caf/tasks/<ID-or-slug>/\`:

- **Ticket ID** → the ID exactly as given (e.g. \`.caf/tasks/GAN-44/\`).
- **Free text** → a short kebab-case slug of the text: lowercase, words joined by \`-\`, at most
  five words, the ones that name the work (e.g. \`add CSV export to the orders page\` →
  \`add-csv-export-orders-page\`). Tell the user the slug: it is the name this work keeps for
  every later artifact.

Don't create the folder yourself — the planner does, in step 4. If the folder already exists,
don't pick another name silently: step 3 decides. For free text only: if the existing
\`requirements.md\` is plainly about a different request, ask the user whether to continue that
one or to use another slug, **STOP** until answered.`;
}

function existingSpecSection() {
  return `## 3. Existing Spec

Read \`.caf/tasks/<ID-or-slug>/requirements.md\` if it exists, and look at its \`Status:\` line.

- **No file** → a new spec. Go to step 4.
- **\`Status: NEEDS_CLARIFICATION\`** → the planner stopped on questions only a human can answer.
  - Every such question has its answer filled in (in the file, or given by the user in chat
    now) → continue: go to step 4 and resume from the existing file. An answer given in chat is
    passed to the planner verbatim; the planner records it, you don't answer for the user.
  - Any is still unanswered → show those questions to the user, **STOP** until answered.
- **\`Status: APPROVED\`** → the spec is a contract. This run does not change its goal, scope or
  acceptance criteria — not even when the argument or the user asks for it. Go to step 4 for the
  task breakdown only; a change the spec seems to need is written as a proposal in
  \`verify-report.md\` in the same folder, for a human to decide.
- **Any other status, or no \`Status:\` line** → tell the user what the file says and continue
  from it in step 4 (the planner decides what is still missing).`;
}

function spawnSection(agentDir) {
  return `## 4. Spawn ${roleLine('caf-planner', agentDir)}

Spawn it with the Task tool. The spawn prompt MUST include:

- The input from step 1: the ticket details, or the free text verbatim — and which of the two
  it is.
- The artifact folder from step 2, with the instruction to use \`<ID-or-slug>\` as its
  \`{TICKET-ID}\` for every artifact.
- What step 3 found: a new spec; or an existing spec to resume, with the answers the user gave
  in chat; or an approved spec — goal, scope and acceptance criteria stay as they are, proposals
  go to \`verify-report.md\`.
- The instruction to follow the spec workflow in the \`## Output\` of its own definition, every
  step in order, and to stop where that workflow says to stop.
- That this is a chat run: a human reads the result and can answer.

Don't add rules of your own to the prompt and don't summarize the planner's: a rule that is
written twice will be changed in only one place.

Wait for the spawn to finish before proceeding to step 5.`;
}

function stopSection() {
  return `## 5. Stop

Read what the planner left in \`.caf/tasks/<ID-or-slug>/\`:

- **\`tasks.md\` is written** → show the user a brief summary: the folder, the status of
  \`requirements.md\`, how many acceptance criteria and tasks, and the assumptions or open
  questions the planner recorded. Then **STOP**.
- **The planner stopped on questions** (\`Status: NEEDS_CLARIFICATION\`, no task breakdown) → show
  the questions, tell the user to answer them and run this command again with the same
  argument. Then **STOP**.
- **Neither** → report exactly what is in the folder and what is missing. Don't write the
  missing file yourself.

Do not start implementation, do not spawn another agent, and do not approve the spec: setting
\`Status: APPROVED\` is the human's decision, made after reading \`requirements.md\`.`;
}

/**
 * caf-plan.md — CAF-SDD-03b3. Hidden: see the note at the top of this file.
 *
 * @param {object} opts
 * @param {string} opts.agentDir  relative path to the agent folder (e.g. `.claude/agents`)
 */
export function buildPlanMd({ agentDir = '.claude/agents' } = {}) {
  return `---
allowed-tools: ${ALLOWED_TOOLS}
description: Write the spec and the task breakdown for a ticket or a free-text request — spawns caf-planner.md (Specify, Clarify, Plan, Tasks), then stops before implementation
argument-hint: [TICKET-ID or free text, e.g. "GAN-44" or "add CSV export to the orders page"]
---

${DRAFT_BANNER}

# Plan (Spec-First)

**This command writes nothing itself and touches no application code.** The only writes are the
planner's, inside \`.caf/tasks/\`. It does not approve the spec and it does not start
implementation.

Purpose: the chat path to the Planner's spec workflow (Specify, Clarify, Plan, Tasks) for one
piece of work, with or without a ticket. The rules of that workflow — the format of
\`requirements.md\`, when to ask a human, how tasks are tied to acceptance criteria — are in the
\`## Output\` of ${roleLine('caf-planner', agentDir)} and are deliberately not repeated here. This
command decides only where the artifacts go and what the planner is given.

${inputSection()}

${folderSection()}

${existingSpecSection()}

${spawnSection(agentDir)}

${stopSection()}

## Constraints

- This command NEVER writes or edits application code, NEVER runs \`git\`, NEVER changes ticket
  status in the tracker and NEVER posts to the tracker or to a PR.
- One source for the planning rules: ${roleLine('caf-planner', agentDir)}. If that file doesn't
  exist, **STOP** and tell the user to generate it with \`caf-init scaffold agents\` — don't plan
  from memory.
- An approved \`requirements.md\` is never edited by this command or by the planner it spawns.
- It ends at \`tasks.md\`. Approving the spec and running the implementation are separate,
  deliberate steps taken by the user.
`;
}

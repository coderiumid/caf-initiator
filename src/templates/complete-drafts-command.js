import { SYNCABLE_SECTIONS } from '../utils/agent-sections.js';

// /caf-complete-drafts (CAF-COMPLETE-DRAFTS-01) — lets the user hand the TODO-filling of freshly
// scaffolded drafts to an AI session without giving up CAF's rules. caf-initiator itself never
// calls a model: it generates this command (same pattern as /caf-feature-catalog-sync and
// /caf-audit-scan), the user runs it in their own AI runner, and `caf-init curate --check-drafts`
// verifies afterwards what code can verify.
//
// What the command text enforces by instruction, and --check-drafts by code:
// - tracked agent sections stay untouched (code-checked against the manifest baseline),
// - verification commands only name scripts that exist (code-checked),
// - no leftover generate-time placeholders (code-checked).
// What only the instructions can protect — and only as far as the human reviews the result —
// is the truth of human-owned content (business context, PRD, ADR reasoning, golden-example
// choice). The command therefore makes the AI ask first and leave the TODO when unanswered;
// don't soften that into "infer a reasonable default".

const DRAFT_BANNER =
  '> DRAFT generated by caf-initiator — review and complete before use, especially the parts\n' +
  '> marked TODO project-specific.';

// No `git add`/`git commit`/`git push`: this command edits documents and stops in the working
// tree for human review. `<pm> run` is only granted when a package manager was detected, so the
// command can run the real verification scripts it documents.
function allowedTools(packageManager) {
  return [
    'Read',
    'Edit',
    'Write',
    'Grep',
    'Glob',
    'Bash(git status:*)',
    'Bash(git diff:*)',
    'Bash(ls:*)',
    ...(packageManager ? [`Bash(${packageManager} run:*)`] : []),
    'Bash(caf-init curate:*)',
    'Bash(npx caf-init curate:*)',
  ].join(', ');
}

function projectShape({ mode, packageManager, apps }) {
  const pm = packageManager
    ? `Package manager: \`${packageManager}\`.`
    : 'Package manager: not detected at generation time — find it yourself before writing any command, and ask the user if it is still unclear.';
  if (mode === 'SINGLE_REPO') {
    const app = apps[0];
    const framework = app?.framework ? `, framework detected: ${app.framework}` : '';
    return [
      `This is a **single-package repo** (\`SINGLE_REPO\`): one package at the repo root${app ? ` (\`${app.name}\`${framework})` : ''}, no workspaces.`,
      pm,
      'Verification commands are the root `package.json` scripts, run unscoped.',
    ].join('\n');
  }
  const list =
    apps.length > 0
      ? apps.map((a) => `- \`${a.path}\` (package \`${a.name}\`${a.framework ? `, ${a.framework}` : ''})`).join('\n')
      : '- no workspace package was detected at generation time — find them yourself and confirm with the user.';
  return [
    'This is a **monorepo** (`MONOREPO`). Workspace packages detected at generation time:',
    '',
    list,
    '',
    pm,
    'Verification commands MUST be scoped to the workspace they belong to (by package name, not folder',
    'path) — never an unscoped root command that fans out to every workspace.',
  ].join('\n');
}

function draftList(drafts) {
  if (!drafts || drafts.length === 0) {
    return '- no draft was found at generation time — list them yourself in step 1.';
  }
  return drafts.map((d) => `- \`${d}\``).join('\n');
}

/**
 * caf-complete-drafts.md
 *
 * @param {object} opts
 * @param {'SINGLE_REPO'|'MONOREPO'} opts.mode   detected repo mode (utils/repo-context.js)
 * @param {string|null} opts.packageManager
 * @param {Array<{name:string,path:string,framework?:string|null}>} opts.apps
 * @param {string} opts.agentDir   relative agent folder (e.g. `.claude/agents`)
 * @param {string[]} opts.drafts   repo-relative draft files that existed when this was generated
 */
export function buildCompleteDraftsMd({
  mode = 'SINGLE_REPO',
  packageManager = null,
  apps = [],
  agentDir = '.claude/agents',
  drafts = [],
} = {}) {
  const trackedSections = Object.keys(SYNCABLE_SECTIONS)
    .map((h) => `\`## ${h}\``)
    .join(', ');

  return `---
allowed-tools: ${allowedTools(packageManager)}
description: Fill in the TODOs left by caf-init in CLAUDE.md, AGENTS.md, agent definitions and docs/ — facts from the code, human decisions only from the user's answers. Never commits.
argument-hint: [optional: limit to one file or area, e.g. "CLAUDE.md" or "docs/"]
---

${DRAFT_BANNER}

# Complete CAF Drafts

This repo was scaffolded with \`caf-init\`. The generated files are drafts full of \`TODO\`s. Your job
is to complete them so the CAF agents (planner, implementation, QA, reviewer) work from correct
context.

**The rule that governs everything below:** these documents are read by agents as the truth on
every ticket, so one wrong claim gets repeated forever. An honest, incomplete document is worth
more than a complete, invented one. If you cannot prove something from the contents of this repo,
leave the \`TODO\` and ask the user.

## Project shape (detected when this command was generated)

${projectShape({ mode, packageManager, apps })}

Re-check these against the repo in step 1 — detection can be stale. If the repo contradicts it,
trust the repo and tell the user.

## Drafts found at generation time

${draftList(drafts)}

## Arguments

\`$ARGUMENTS\` — optional, limit the work to one file or area. If empty, cover every draft above
plus any \`docs/\` reference document that exists.

## Steps

### 1. Read — do not write anything yet

- The code: \`package.json\` (every workspace's, in a monorepo), framework config, folder layout, a
  few representative files in each main folder, test setup, lint/format config, CI config, README.
- Every draft listed above, plus \`.caf/**\`, \`${agentDir}/*.md\` and \`docs/**\` as they are now.

### 2. Report the plan and your questions — then STOP

Tell the user:
- which files you will fill and which parts you can prove from the code,
- which parts are human decisions (see "Never invent" below), as specific questions grouped per
  document so they can be answered briefly.

**STOP here and wait for the user's answers.** Do not start writing until they reply. A question
they leave unanswered stays a \`TODO\` (or becomes an explicit open question in the document).

### 3. Fill in the drafts

#### Fill directly from the code — every claim must point at a real file

\`CLAUDE.md\`
- **Verification Commands**: only scripts that actually exist in \`package.json\`, by their exact
  names. If typecheck/lint/test has no script of its own, record that as a gap — never write a
  command that does not exist.
- **Code Conventions**: patterns that are genuinely consistent in the code (folder structure,
  naming, API calls, error/loading handling, state, styling), specific to this project — not
  general framework advice. Where the code is inconsistent, say so and ask which pattern is right.
- **Database**: what the repo actually shows. If this repo has no database of its own, say that.
- Keep the file under roughly 150 lines.

\`AGENTS.md\`
- **Concrete Rules**: 3–6 rules visible in the code, each with a right example taken from a real
  file (cite its path) and a realistic wrong example.

\`${agentDir}/*.md\`
- Fill only \`## Role\`, \`## Scope\` and \`## Verify Checklist\`, and only where a \`TODO\` remains.
- **Do NOT change** ${trackedSections}, or the frontmatter. These sections are tracked by
  \`caf-init curate\`: an edit there stops future template fixes from reaching this file, and
  their report/status formats are parsed word-for-word by caf-orchestrator.
- Leave every \`TODO\` about MCP servers alone — that is a security decision for a human.

\`docs/architecture/system-overview.md\`, \`docs/testing-strategy.md\`, \`docs/api-contract.md\`
(only the ones that already exist)
- Describe what the code shows; mark every part that is an inference as an inference.
- Testing strategy: the tooling and patterns that exist, and what is missing. Coverage targets
  and policy are the user's call.
- API contract: if this repo only *consumes* an API, document only the endpoints it actually
  calls (with the calling file), label the document as the consumer's view, and never invent
  response fields the code does not use.
- \`docs/schema/erd.md\`: fill only if this repo owns a schema. Otherwise leave it alone and say so.

#### Never invent — ask, then write only from the user's answers

- **Business Context** in \`CLAUDE.md\`: domain, users, business constraints.
- \`docs/product/prd.md\`: problem, target users, success criteria, scope.
- \`docs/product/features/*.md\`: you may describe existing behavior from the code; the goal and
  acceptance criteria come from the user.
- \`.caf/knowledge/golden-examples/**/RULES.md\`: you may propose candidate files per pattern with
  your reasoning; the user picks them and decides the do/don't.
- \`.caf/knowledge/decisions/\` (ADRs): you may list the technical decisions that are visible; the
  *why* comes from the user.
- Any rule or convention the code does not already follow.

#### Hard limits

- Documents only. Do not touch application code, \`package.json\` or config files.
- Do not remove any \`DRAFT\` banner — the user removes it after reviewing.
- Do not create a document that does not exist yet without asking first.
- Do not leave a generate-time double-curly placeholder (an app-name, apps-dir or repo-mode token
  in double curly braces). The per-ticket tokens \`{{TICKET-ID}}\` and \`{{feature-name}}\` are
  intentional and must stay exactly as they are.
- Do not \`git add\`, commit or push. Stop in the working tree.

### 4. Verify

1. Run \`caf-init curate --check-drafts\` (use however \`caf-init\` is invoked in this environment,
   e.g. \`npx caf-init\`). It fails on: a tracked agent section that changed, a verification
   command whose script does not exist, a leftover placeholder, a golden-example path that does
   not exist. Fix every \`FAIL\` by correcting the document — for a changed tracked section,
   restore its original text. If you cannot run it, say so and ask the user to run it.
2. Run the verification scripts you documented (lint, typecheck, test) and note the results. If
   one fails, report it — do not fix application code.
3. \`git diff\` must touch documents only, and in \`${agentDir}/*.md\` only Role, Scope and Verify
   Checklist.

### 5. Report

Briefly: files changed, \`TODO\`s still open and why, questions still unanswered, the
\`--check-drafts\` result, and anything in the code that looked inconsistent or suspicious.
`;
}

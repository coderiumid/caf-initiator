// CAF-SDD-03a — the builders of the kinds that are due to be retired or replaced are frozen.
//
// Why a golden copy here, against the usual "render from the same function" rule: for a tracked
// section `curate sync` treats any difference between the template and an untouched file as
// DRIFT and rewrites the file. A wording change in one of these builders therefore lands in
// every repo that already has that agent. These kinds are not supposed to change again, so
// needing two edits (builder + golden) to change them is the point.
//
// The golden files in test/fixtures/frozen-kinds/ were written once from the builders' output
// and are never regenerated by a test.

import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';

import { agentsSync } from '../src/commands/agents-sync.js';
import {
  SYNCABLE_SECTIONS,
  detectKind,
  parseSections,
  sectionBody,
  templateForExistingSection,
} from '../src/utils/agent-sections.js';
import { readManifest, getBaselineHash, setSectionBaseline, writeManifest } from '../src/utils/generate-manifest.js';
import { hashSection, compareSection, SECTION_STATUS } from '../src/utils/section-diff.js';
import { copyFixture } from './helpers/make-repo.js';
import { silenced } from './helpers/mono-snapshot.js';
import {
  FROZEN,
  GOLDEN_DIR,
  AGENT_DIR,
  fixtureDir,
  renderAgents,
  goldenOf,
  goldenPath,
  trackedSections,
} from './helpers/frozen-kinds.js';

const FROZEN_MESSAGE =
  'builder kind ini dibekukan (CAF-SDD-03a): perubahan pada section ter-track menimpa file agent ' +
  'lama lewat DRIFT saat `curate sync`. If the change is intended, it needs its own ticket and a ' +
  'deliberate edit of the golden file — do not regenerate the golden to make this pass.';

const rendered = {
  'mono-pnpm': await renderAgents('mono-pnpm'),
  'single-nuxt': await renderAgents('single-nuxt'),
};

function baselineEverySection(manifest, relPath, content) {
  const { lines, sections } = parseSections(content);
  for (const s of sections) {
    setSectionBaseline(manifest, relPath, s.header, hashSection(sectionBody(lines, s)));
  }
}

/** Temp copy of the fixture holding one generated + baselined agent file. */
function makeBaselinedRepo(fixture, { file, content }) {
  const dir = copyFixture(fixtureDir(fixture), 'caf-frozen-kinds-');
  const relPath = path.join(AGENT_DIR, file);
  fs.mkdirSync(path.join(dir, AGENT_DIR), { recursive: true });
  fs.writeFileSync(path.join(dir, relPath), content, 'utf8');
  const manifest = { version: 1, files: {} };
  baselineEverySection(manifest, relPath, content);
  writeManifest(dir, manifest);
  return { dir, relPath };
}

/**
 * Status of every tracked section of the agent file on disk, the way agents-sync.js computes it.
 * A section the template has but the file lacks is reported as MISSING (sync would prompt to add
 * it — also a change to an existing file).
 */
function sectionStatuses(dir, relPath) {
  const content = fs.readFileSync(path.join(dir, relPath), 'utf8');
  const manifest = readManifest(dir);
  const kind = detectKind(relPath);
  const bodies = trackedSections(content);
  const out = {};
  for (const header of Object.keys(SYNCABLE_SECTIONS)) {
    const proposed = SYNCABLE_SECTIONS[header](kind);
    if (proposed == null) continue;
    if (!(header in bodies)) {
      out[header] = 'MISSING';
      continue;
    }
    const baselineHash = getBaselineHash(manifest, relPath, header);
    const template = templateForExistingSection(header, kind, bodies[header]);
    out[header] = compareSection({
      baselineHash,
      currentHash: hashSection(bodies[header]),
      templateHash: template == null ? baselineHash : hashSection(template),
    });
  }
  return out;
}

test('AC-3: golden directory holds exactly one file per frozen kind + fixture', () => {
  const expected = FROZEN.map(({ kind, fixture }) => path.basename(goldenPath(kind, fixture))).sort();
  assert.deepEqual(fs.readdirSync(GOLDEN_DIR).sort(), expected);
  assert.equal(expected.length, 15, '7 kinds on both fixtures + implementer on single-nuxt');
});

for (const { kind, fixture } of FROZEN) {
  test(`AC-3: ${kind} on ${fixture} renders exactly the golden tools + tracked sections`, () => {
    const agent = rendered[fixture][kind];
    assert.ok(agent, `${kind} is no longer rendered for ${fixture}. ${FROZEN_MESSAGE}`);
    const golden = JSON.parse(fs.readFileSync(goldenPath(kind, fixture), 'utf8'));
    assert.deepEqual(goldenOf({ kind, fixture, ...agent }), golden, `${agent.file} (${fixture}): ${FROZEN_MESSAGE}`);
  });
}

// The false DRIFTs this test used to list as known exceptions (pm / ux-designer `Working Pattern
// (PIV)`, qa `Input` in a monorepo) were fixed at the root in CAF-SDD-03a2, so there is no
// exception table any more: every frozen kind must come through `curate sync` untouched.
test('AC-2: after generate + baseline, every tracked section of every frozen kind is IN_SYNC and curate sync writes nothing', async () => {
  const notInSync = [];

  for (const { kind, fixture } of FROZEN) {
    const agent = rendered[fixture][kind];
    const label = `${agent.file} (${fixture})`;
    const { dir, relPath } = makeBaselinedRepo(fixture, agent);
    const filePath = path.join(dir, relPath);

    for (const [section, status] of Object.entries(sectionStatuses(dir, relPath))) {
      if (status !== SECTION_STATUS.IN_SYNC) notInSync.push(`${kind} | ${fixture} | ${section} | ${status}`);
    }
    // MISSING would open an interactive prompt in agentsSync; it is already recorded above.
    if (Object.values(sectionStatuses(dir, relPath)).includes('MISSING')) continue;

    for (const dryRun of [true, false]) {
      const mode = dryRun ? 'dry-run' : 'write';
      const result = await silenced(() => agentsSync({ dir, agentDir: AGENT_DIR, dryRun }));
      assert.deepEqual(result.drifted, [], `${label} (${mode}): drifted list`);
      assert.deepEqual(result.needsAttention, [], `${label} (${mode}): needsAttention`);
      assert.deepEqual(result.unverifiable, [], `${label} (${mode}): unverifiable`);
      assert.deepEqual(result.updated, [], `${label} (${mode}): must not be reported as updated`);
      assert.equal(
        fs.readFileSync(filePath, 'utf8'),
        agent.content,
        `${label} (${mode}): must stay byte-identical after curate sync. ${FROZEN_MESSAGE}`
      );
    }
  }

  assert.deepEqual(
    notInSync,
    [],
    'the set of non-IN_SYNC tracked sections (kind | fixture | section | status) must be empty. ' +
      'A row here is a new DRIFT: `curate sync` would now overwrite that section in existing repos.'
  );
});
